# บริบทที่ผู้ใช้เป็นครู ("ผู้ปกครองนักเรียน") ไม่ใช่ครอบครัวของผู้ใช้
TEACHER_CONTEXT = ["ผู้ปกครองนักเรียน", "ผู้ปกครองของนักเรียน", "พ่อแม่นักเรียน", "พ่อแม่ของนักเรียน"]

# คำปฏิเสธที่อยู่ "ก่อน" คำกดดันไม่เกิน NEG_WINDOW ตัวอักษร เช่น "ไม่ได้กดดัน" "ไม่เคยบังคับ"
NEG_PREFIXES = ("ไม่ได้", "ไม่เคย", "ไม่ค่อย", "ไม่", "มิได้")
NEG_WINDOW = 8


def _find_unnegated(text: str, word: str) -> bool:
    pos = text.find(word)
    while pos >= 0:
        before = text[max(0, pos - NEG_WINDOW):pos].replace(" ", "")
        if not before.endswith(NEG_PREFIXES) and not any(n + "ค่อย" in before for n in ("ไม่",)):
            return True
        pos = text.find(word, pos + 1)
    return False


def _has_person(text: str, group: str) -> str | None:
    for w in PERSON_WORDS[group]:
        if w in text:
            return w
    return None


def detect_root_cause(text: str, context: str = "") -> dict | None:
    """คืน {'topic', 'person', 'pressure'} ถ้าข้อความบอกว่า "คน" เป็นต้นตอความกดดัน ไม่อย่างนั้นคืน None
    v22 context = ข้อความก่อนหน้า 1 ข้อความ: ถ้าข้อความนี้มีแรงกดดันแต่ไม่บอกว่าใคร (เช่น "เค้าบอกถ้าตกจะไม่จ่ายค่าเรียน")
    แล้วข้อความก่อนหน้าพูดถึงคนนั้น ("แม่...") ก็ใช้คนจากข้อความก่อนหน้า (คำกดดันต้องอยู่ในข้อความนี้เสมอ)"""
    t = (text or "").lower()
    ctx = (context or "").lower()
    for group, topic, pressure_words in ROOT_RULES:
        if group == "family" and any(x in t or x in ctx for x in TEACHER_CONTEXT):
            continue  # ครูพูดถึง "ผู้ปกครองนักเรียน" ไม่ใช่ครอบครัวของผู้ใช้
        person = _has_person(t, group) or (_has_person(ctx, group) if ctx else None)
        if not person:
            continue
        for w in pressure_words:
            if _find_unnegated(t, w):
                return {"topic": topic, "person": person, "pressure": w}
    return None
