    last = users[-1] if users else ""
    before = users[:-1]
    low = last.lower()
    all_text = " ".join(users)

    def find_subject(t):
        hit = _first(t, [w for w, _ in SUBJECTS])
        return dict(SUBJECTS)[hit] if hit else None

    worries_of = kinds_of
    worries = worries_of(low)
    continuing = False
    if not worries and before and (len(_strip_fillers(low)) <= 60 or not _first(low, [w for w, _ in SUBJECTS])):
        # ข้อความสั้นที่ตอบคำถามของบอทต่อจากเรื่องเดิม (เช่น "แทบทุกวัน" "แล้วต้องทำไง") -> ยังเป็นเรื่องเดิม
        for t in reversed(before[-3:]):
            prev_w = worries_of(t)
            if prev_w:
                worries, continuing = [w for w in prev_w if w not in ("ability",)], True
                break
    ability_verb = None
    m = re.search(r"(?:กลัวว่าจะ|กลัวจะ|กลัว|ว่าจะ|คงจะ|คง)\s*(\S{2,14}?)(ไม่ได้|ไม่สำเร็จ|ไม่ทัน|ไม่รอด|ไม่ไหว)", low)
    if m:
        ability_verb = m.group(1)
    tm = TIME_RE.search(last)
    deadline = _first(last, DEADLINE)
    freq = FREQ_RE.search(last)
    feeling = _first(low, FEELINGS)
    return {
        "last": last, "before": before, "all": all_text, "turn": len(users),
        "subject": find_subject(last), "subject_before": next((find_subject(t) for t in reversed(before) if find_subject(t)), None),
        "person": _first(last, PEOPLE), "person_before": next((_first(t, PEOPLE) for t in reversed(before) if _first(t, PEOPLE)), None),
        "worries": worries, "ability_verb": ability_verb,
        "time": tm.group(0) if tm else None, "deadline": deadline, "freq": freq.group(0) if freq else None,
        "audience": _first(last.replace("ในห้องน้ำ", "_"), AUDIENCE), "feeling": feeling, "strong": any(w in low for w in STRONG),
        "context_worries": sorted({k for t in users[-3:] for k in worries_of(t)} | set(worries)),
        "school_avoid": "ไม่อยากไปโรงเรียน" in low or "ไม่อยากไปเรียน" in low, "continuing": continuing,
    }


