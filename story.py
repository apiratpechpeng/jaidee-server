    """สะท้อนด้วยคำของผู้ใช้ + ท้ายประโยคตามหัวข้อ (ใช้เมื่อ reflect() อ่านชนิดความกังวลไม่ออก)"""
    if not topic or st["continuing"]:
        return None
    last = st["last"]
    echo = to_you(last if len(last) <= 70 else _clause(last, _first(last, [w for w, _ in SUBJECTS] + PEOPLE) or "", 70))
    echo = re.sub(r"\s*(ทำไงดี|ทำยังไงดี|ควรทำยังไงดี|ควรทำไงดี)$", "", echo).strip()
    if len(echo) < 3:
        return None
    tail = next((t for topics, t in GENERIC_TAIL if topic in topics), "ฟังแล้วรู้สึกได้ว่ามันหนักใจอยู่นะครับ")
    if len(echo) <= 10:
        return f"{echo}สินะครับ {tail}"
    return f"{echo} {tail}"
