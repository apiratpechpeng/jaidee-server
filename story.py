def clean(text: str) -> str:
    t = (text or "").strip()
    for a, b in TYPO.items():
        t = t.replace(a, b)
    return re.sub(r"\s+", " ", t)


def _strip_fillers(t: str) -> str:
    """ตัดคำเสริมที่ไม่มีความหมาย: "แบบว่า" ทุกที่, "คือ" ต้นประโยค, "อะ/ครับ/ค่ะ/555" ท้ายประโยค (ไม่ตัดกลางคำ เช่น "เยอะ")"""
    t = re.sub(r"แบบว่า|คือว่า", " ", t)
    t = re.sub(r"^\s*คือ\s*", "", t)
    t = re.sub(r"(\s|^)คือ\s", " ", t)
    for _ in range(3):
        t = re.sub(r"\s*(อ่ะ|อะ|นะคะ|นะครับ|ครับ|ค่ะ|คะ|จ้า|จ้ะ|555+)\s*$", "", t.strip())
    return re.sub(r"\s+", " ", t).strip()


def to_you(t: str) -> str:
    """เปลี่ยนคำแทนตัวผู้ใช้เป็นคำที่บอทใช้ เช่น "แม่เรา" -> "แม่ของคุณ", "เรากลัว" -> "กลัว" """
    t = _strip_fillers(t)
    for w in SELF_WORDS:
        t = t.replace("ถึงตัว" + w, "ถึงตัวคุณ")  # "ถึงเนื้อถึงตัวเรา" (ไม่ให้เหลือ "ถึงคุณ")
    for w in SELF_WORDS:
        for p in PEOPLE + ["เพื่อน"]:
            t = t.replace(p + " " + w, p + "ของคุณ").replace(p + w, p + "ของคุณ")
    for w, _ in SUBJECTS:
        t = t.replace(w + "เรา", w + "ของคุณ").replace(w + "ฉัน", w + "ของคุณ")
    for p in PEOPLE:
        t = t.replace(p + "ก็", p)
    t = re.sub(r"(ให้|ว่า|กับ|ของ|ใส่|ถึง|ล้อ|แกล้ง|ด่า|เรียก|ฟัง|กอดคอ|กอด|สนใจ|รัก|เห็น|ชม|เข้าใจ|ช่วย|ฟัง|ชวน|ทิ้ง|เมิน|เลิกกับ)(" + "|".join(SELF_WORDS) + r")", r"\1คุณ", t)
    t = re.sub(r"(ตอนนี้|ช่วงนี้|วันนี้|เมื่อวาน|แล้ว|แต่|และ|เพราะ|ก็)(" + "|".join(SELF_WORDS) + r")", r"\1", t)
    t = re.sub(r"^(" + "|".join(SELF_WORDS) + r")\s*", "", t)
    t = re.sub(r"\s(" + "|".join(SELF_WORDS) + r")(?=\S)", " ", t)
    t = re.sub(r"^(แต่|และ|แล้ว|ก็|เพราะ)\s*", "", t.strip())
    t = re.sub(r"^(ตอนนี้|ช่วงนี้)\s*", "", t)
    t = re.sub(r"\s*(ด้วย|อีกแล้ว|อีก)$", "", t)  # "ทะเลาะกับแม่ด้วย" -> "ทะเลาะกับแม่"
    return re.sub(r"\s+", " ", t).strip(" ,.!?")


_MASK = ["อย่า", "แม่น้ำ", "แม่ค้า", "พ่อค้า", "ตายาย"]


def _first(text: str, words) -> str | None:
    if words is PEOPLE:
        for m in _MASK[:-1]:
            text = text.replace(m, "_" * len(m))
    best = None
    for w in words:
        p = text.find(w)
        if p >= 0 and (best is None or p < best[0] or (p == best[0] and len(w) > len(best[1]))):
            best = (p, w)
    return best[1] if best else None


def _clause(text: str, key: str, max_len: int = 70) -> str:
    """ท่อนข้อความรอบคำสำคัญ (ตัดตามช่องว่าง) ไว้สะท้อนกลับด้วยคำของผู้ใช้"""
    if not key:
        return text[:max_len]
    parts = [p for p in re.split(r"\s+|,|ๆ\s", text) if p]
    for i, p in enumerate(parts):
        if key in p:
            out = p
            j = i + 1
            while j < len(parts) and len(out) + 1 + len(parts[j]) <= max_len and not any(s in parts[j] for s in ("ควร", "ทำไงดี", "ยังไงดี")):
                out += " " + parts[j]
                j += 1
            k = i - 1
            while k >= 0 and len(out) + 1 + len(parts[k]) <= max_len and len(parts[k]) <= 12:
                out = parts[k] + " " + out
                k -= 1
            return out
    return text[:max_len]


