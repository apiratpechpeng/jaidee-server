def _hist(text):
    return [{"sender": "user", "content": text}]


def _keyword_only(text):
    return detect_topic_info(_hist(text), use_nlp=False)["topic"]


def _hybrid(text):
    return detect_topic(_hist(text))


def run(verbose=False):
    results = {}
    for name, fn in (("keyword อย่างเดียว (แบบเดิม)", _keyword_only), ("keyword + NLP (แบบใหม่)", _hybrid)):
        wrong = [(t, exp, fn(t)) for t, exp in CASES if fn(t) != exp]
        ok = len(CASES) - len(wrong)
        results[name] = ok
        print(f"{name}: ถูก {ok}/{len(CASES)} ข้อ ({ok * 100 / len(CASES):.0f}%)")
        if verbose:
            for t, exp, got in wrong:
                print(f"    ✗ {t}  -> ได้ {got}  ควรเป็น {exp}")
    crisis_ok = all(detect_sentiment(t) == "crisis" for t in CRISIS_CASES)
    print("ข้อความวิกฤตยังถูกจับครบ:", "ผ่าน" if crisis_ok else "ไม่ผ่าน!")
    # บทสนทนาต่อเนื่อง: ข้อความล่าสุดไม่มีเนื้อหา ต้องใช้หัวข้อจากข้อความก่อนหน้า
    follow = [{"sender": "user", "content": "เพื่อนยืมเงินไปแล้วไม่ยอมคืน"}, {"sender": "ai", "content": "..."},
              {"sender": "user", "content": "แล้วควรทำยังไงดีครับ"}]
    follow_ok = detect_topic(follow) == "friend_money"
    print("บทสนทนาต่อเนื่อง (ถามต่อว่าควรทำไงดี):", "ผ่าน" if follow_ok else "ไม่ผ่าน!")
    # v16 หัวข้อหลัก/รอง + ถามสำรวจ
    ov_ok = 0
    for text, primary, secondary, clarify in OVERLAP_CASES:
        i = detect_topic_info(_hist(text))
        good = i["topic"] == primary and (secondary is None or i["secondary_topic"] == secondary) and i["needs_clarify"] == clarify
        ov_ok += good
        if verbose and not good:
            print(f"    ✗ {text} -> หลัก {i['topic']} รอง {i['secondary_topic']} ถามสำรวจ {i['needs_clarify']}")
    print(f"ประโยคซ้อนทับ (หลัก/รอง/ถามสำรวจ): ถูก {ov_ok}/{len(OVERLAP_CASES)} ข้อ")
    from .topic_examples import OVERLAP_EXAMPLES
    ex_ok = sum(detect_topic_info(_hist(t))["topic"] == p for t, p, _ in OVERLAP_EXAMPLES)
    print(f"ตัวอย่างซ้อนทับใน topic_examples.OVERLAP_EXAMPLES: ถูก {ex_ok}/{len(OVERLAP_EXAMPLES)} ข้อ")
    mt_ok = 0
    for msgs, expected in MULTITURN_CASES:
        h = []
        for m in msgs:
            h += [{"sender": "user", "content": m}, {"sender": "ai", "content": "..."}]
        got = detect_topic(h[:-1])
        mt_ok += got == expected
        if verbose and got != expected:
            print(f"    ✗ {' || '.join(msgs)} -> {got} ควรเป็น {expected}")
    print(f"บทสนทนาหลายข้อความ (เปลี่ยนหัวข้อตามบริบท): ถูก {mt_ok}/{len(MULTITURN_CASES)} ข้อ")
    return results, crisis_ok and follow_ok


