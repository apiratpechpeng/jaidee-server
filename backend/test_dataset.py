def run(cases) -> tuple[int, int]:
    total = ok = 0
    for name, turns in cases:
        h, prev = [], []
        print(f"\n== {name}")
        for text, rule in turns:
            r = _run(h, prev, text)
            bad = check(r, rule)
            joined = " ".join(r["parts"])
            for w in rule.get("all", []):
                if w not in joined:
                    bad.append(f"ไม่ได้พูดถึง '{w}'")
            if "any" in rule and not any(w in joined for w in rule["any"]):
                bad.append(f"ไม่มีคำใดใน {rule['any']}")
            total += 1
            ok += not bad
            print(("  ✓ " if not bad else "  ❌ ") + text)
            for p in r["parts"]:
                print("      บอท:", p)
            for b in bad:
                print("      ->", b)
    print(f"\nสรุป: ผ่าน {ok}/{total} ข้อ")
    return ok, total


def main() -> int:
    cases = S
    if len(sys.argv) > 1 and sys.argv[1] == "blind5":
        from .eval_data.v25.blind5 import S as cases  # ชุดลับ: รันเพื่อรายงานผลเท่านั้น
    if len(sys.argv) > 1 and sys.argv[1] == "blind6":
        from .eval_data.v26.blind6 import S as cases  # ชุดลับ v26: รันเพื่อรายงานผลเท่านั้น
    ok, total = run(cases)
    return 0 if ok == total else 1


if __name__ == "__main__":
    sys.exit(main())
