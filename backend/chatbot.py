# v16: หัวข้อหลัก/หัวข้อรอง + ความมั่นใจ + ควรถามสำรวจก่อนไหม
# ---------------------------------------------------------------------
# หัวข้อ "เรื่องงาน/การเรียน" ที่มักเป็นแค่เรื่องหน้าฉาก ถ้าผู้ใช้ยังไม่บอกต้นตอ ควรถามสำรวจก่อนให้คำแนะนำ
TASK_TOPICS = {"study_stress", "exam_fail", "group_work", "workload", "no_way_out_workload", "parttime_work", "future"}
SWITCH_KW_MIN = 3        # keyword ของหัวข้อใหม่ในข้อความล่าสุดต้องได้อย่างน้อยเท่านี้จึงสลับหัวข้อ
SECONDARY_MIN = 0.18     # หัวข้อรองต้องได้คะแนนรวมอย่างน้อยเท่านี้ (หรือมี keyword ตั้งแต่ 3 ขึ้นไป)
CLARIFY_MAX_LEN = 30     # ข้อความแรกที่สั้นกว่านี้ (ไม่นับคำลงท้าย) และยังไม่บอกต้นตอ -> ถามสำรวจก่อน


def detect_topic_info(history: list[dict], classifier=None, use_nlp: bool = True, _prev="auto") -> dict:
    """จับหัวข้อ คืน dict
      topic / primary_topic   หัวข้อหลัก (ต้นตอ ถ้าระบุได้)
      secondary_topic         หัวข้อรอง (เรื่องที่หยิบมาเล่า/บริบทประกอบ) หรือ None
      confidence              0-1 โดยประมาณ (keyword ชัด/ต้นตอชัด = สูง, NLP เดาอ่อนๆ = ต่ำ)
      needs_clarify           True = ข้อความแรก สั้น/กำกวม และยังไม่บอกต้นตอ -> ควรถามสำรวจก่อน
      source                  keyword / root_cause / context_shift / keyword+nlp / context / gemini / keyword-weak / none
    (คีย์เดิม topic, source, kw_score, score, prev_topic ยังอยู่ครบ โค้ดส่วนอื่นใช้ได้เหมือนเดิม)"""
    info = _detect_core(history, classifier, use_nlp, _prev)
    kw = info.pop("_kw", {}) or {}
    nlp = info.pop("_nlp", {}) or {}
    combined = info.pop("_combined", None) or {t: nlp.get(t, 0.0) + KW_WEIGHT * kw.get(t, 0) for t in set(nlp) | set(kw)}
    primary = info.get("topic")
    prev_topic = info.get("prev_topic")

    # หัวข้อรอง
    secondary = None
    if info.get("source") in ("root_cause", "context_shift") and prev_topic and prev_topic != primary:
        secondary = prev_topic  # เรื่องที่คุยอยู่ก่อน คือบริบทของต้นตอใหม่
    if not secondary:
        for t, sc in _ranked(combined):
            if t != primary and (sc >= SECONDARY_MIN or kw.get(t, 0) >= 3):
                secondary = t
                break

    # ความมั่นใจ
    src = info.get("source")
    if src in ("keyword", "root_cause", "context_shift"):
        confidence = 0.85
    elif src == "gemini":
        confidence = 0.7
    elif primary:
        confidence = round(min(0.8, max(0.2, combined.get(primary, 0.0) * 2.5)), 2)
    else:
        confidence = 0.0

    # ควรถามสำรวจก่อนไหม (เฉพาะข้อความแรกของเรื่อง: ยังไม่มีหัวข้อก่อนหน้า)
    from .nlp import content_length
    last_text = next((m["content"] for m in reversed(history) if m["sender"] == "user"), "")
    needs_clarify = bool(
        primary and not prev_topic and src != "root_cause" and use_nlp
        and (primary in TASK_TOPICS or confidence < 0.4)
        and (content_length(last_text) < CLARIFY_MAX_LEN or confidence < 0.4)
        and "เพราะ" not in last_text
    ) or bool(
        # v22 ขอคำแนะนำตั้งแต่ข้อความแรกแต่ยังเล่าน้อยมาก (เช่น "ถูกเพื่อนชวนอีกแล้ว ไม่รู้จะทำไงดี") -> ถามก่อนว่าเกิดอะไรขึ้น
        primary and not prev_topic and src not in ("root_cause",) and use_nlp
        and is_advice_request(last_text) and content_length(last_text) < 20
    )
    info.update({"primary_topic": primary, "secondary_topic": secondary, "confidence": confidence,
                 "needs_clarify": needs_clarify})
    return info


def detect_topic(history: list[dict], classifier=None) -> str | None:
    """คืนเฉพาะชื่อหัวข้อ (ดูรายละเอียดใน detect_topic_info)"""
    return detect_topic_info(history, classifier)["topic"]


def _said_key(option: str) -> str:
    """ข้อความช่วงต้นของประโยคที่ใช้เช็กว่าเคยพูดไปแล้วหรือยัง (ตัด 'ถ้าไหว ' ที่ถูกตัดทิ้งตอนพูดออกก่อน)"""
    return option.removeprefix("ถ้าไหว ")[:25]


def _pick(options, used_text: str, max_len: int | None = None):
    """เลือกข้อที่ยังไม่เคยพูดในบทสนทนานี้ก่อน ถ้าใช้หมดค่อยสุ่มซ้ำ
    ถ้าระบุ max_len จะเลือกเฉพาะข้อที่ไม่ยาวเกินนั้นก่อน (เพื่อให้ลงกล่องเดียวได้) ถ้าไม่มีข้อไหนสั้นพอ ใช้ข้อที่สั้นที่สุด"""
    pool = [o for o in options if _said_key(o) not in used_text] or list(options)
    if max_len:
        fit = [o for o in pool if len(o) <= max_len]
        if not fit:
            fit = [o for o in options if len(o) <= max_len]
        pool = fit or [min(options, key=len)]
    return random.choice(pool)


def _pick_many(options, n, used_text: str, max_len: int | None = None):
    chosen = []
    for _ in range(n):
        remaining = [o for o in options if o not in chosen]
        if not remaining:
            break
        chosen.append(_pick(remaining, used_text, max_len))
    return chosen


def _option_pieces(opts: list[str]) -> list[str]:
    """ทางเลือกทีละข้อ ข้อแรกขึ้นต้น 'อย่างแรก' ข้อที่สองขึ้นต้น 'อย่างที่สอง' (ตัด 'ถ้าไหว' ที่ซ้ำออก)"""
    ordinals = ["อย่างแรก", "อย่างที่สอง", "อีกอย่างคือ"]
    pieces = []
    for i, o in enumerate(opts):
        o = o[len("ถ้าไหว "):] if o.startswith("ถ้าไหว ") else o
        pieces.append(f"{ordinals[min(i, 2)]} {o}" + ("" if o.endswith("ครับ") else "ครับ"))
    return pieces


def _option_line(kb, used_text: str, max_len: int) -> str:
    """ทางเลือกเล็กๆ 1 ข้อ ในรูปประโยคพร้อมใช้ (ใส่ 'ถ้าอยากลองดู' นำหน้าถ้าจำเป็น และลงท้าย 'ครับ')"""
    opt = _pick(kb["options"], used_text, max_len)
    lead = "" if opt.startswith(("ถ้า", "ลอง")) else "ถ้าอยากลองดู "
    return lead + opt + ("" if opt.endswith("ครับ") else "ครับ")


def _try_one_box(kb, used_text: str, allow_options: bool = True) -> str | None:
    """ประกอบคำตอบ "กล่องเดียว" ให้ยาวไม่เกิน MAX_LONG_CHARS (~7 บรรทัด)
    เนื้อหาต่อหัวข้อค่อนข้างยาว จึงลองรูปแบบเรียงจากครบไปหาสั้น แล้วเลือกจากรูปแบบที่ "พอดี" ได้จริง
      F=สะท้อนความรู้สึก W=ปกป้องคุณค่า O=ทางเลือกเล็กๆ Q=คำถาม
      FWOQ (ครบ 4 ขั้น) / FWQ / FOQ / FQ (สั้นสุด พอดีเสมอ)
    ถ้ามีหลายรูปแบบที่พอดี จะสุ่ม (ยกเว้น FQ ที่ใช้เมื่อไม่มีทางเลือกอื่น) และเลือกประโยคที่ยังไม่เคยพูดก่อน"""
    options = [_option_text(o) for o in kb["options"]]
    pools = {"F": kb["feel"], "W": kb["worth"], "O": options, "Q": kb["questions"]}
    classes = []
    for template in (("FWOQ", "FWQ", "FOQ", "FQ") if allow_options else ("FWQ", "FQ")):
        combos = [c for c in itertools.product(*(pools[k] for k in template)) if len(" ".join(c)) <= MAX_LONG_CHARS]
        if combos:
            classes.append(combos)
    if not classes:
        return None
    full = classes[0] if len(classes[0][0]) == 4 else None
    chosen_class = full or random.choice(classes[:-1] if len(classes) > 1 else classes)
    fresh = [c for c in chosen_class if all(piece[:25] not in used_text for piece in c)]
    return " ".join(random.choice(fresh or chosen_class))


def _option_text(opt: str) -> str:
    lead = "" if opt.startswith(("ถ้า", "ลอง")) else "ถ้าอยากลองดู "
    return lead + opt + ("" if opt.endswith("ครับ") else "ครับ")


def _avoid_repeats(parts: list[str], kb, used_text: str) -> list[str]:
    """กล่องไหนเคยพูดไปแล้วในบทสนทนานี้ ให้สลับเป็นประโยคชนิดเดียวกันที่ยังไม่เคยพูด
    (เช่น คำถามซ้ำ -> คำถามอื่น) ถ้าชนิดนั้นหมดแล้วใช้ชนิดอื่นที่ยังไม่เคยพูด ถ้าไม่เหลืออะไรเลยค่อยยอมซ้ำ
    ใช้กับรูปแบบ 2-3 กล่องเท่านั้น (ดูใน _build_reply)"""
    kinds = {
        "feel": list(kb["feel"]), "worth": list(kb["worth"]),
        "option": [_option_text(o) for o in kb["options"]], "question": list(kb["questions"]),
    }

    def kind_of(text):
        for k, items in kinds.items():
            if any(i[:25] in text for i in items):
                return k
        return None

    def fresh(items, taken):
        return [i for i in items if i[:25] not in used_text and len(i) <= MAX_BUBBLE_CHARS and all(i[:25] not in t for t in taken)]

    out = []
    for part in parts:
        if part[:25] not in used_text:
            out.append(part)
            continue
        kind = kind_of(part)
        pool = fresh(kinds.get(kind, []), out + parts)
        if not pool:
            pool = fresh([x for k, items in kinds.items() if k != "feel" for x in items], out + parts)
        out.append(random.choice(pool) if pool else part)
    return out


def _prev_layout(history: list[dict]) -> str | None:
    """เดารูปแบบที่บอทตอบรอบก่อน จากจำนวนกล่อง ai ที่ต่อท้ายประวัติ (ใช้เลี่ยงตอบรูปแบบเดิมซ้ำติดกัน)"""
    n, last_len = 0, 0
    msgs = list(reversed(history))
    while msgs and msgs[0]["sender"] != "ai":
        msgs.pop(0)  # ข้ามข้อความล่าสุดของผู้ใช้ (ตอนเรียกฟังก์ชันนี้ ประวัติจะลงท้ายด้วยข้อความของผู้ใช้เสมอ)
    for m in msgs:
        if m["sender"] != "ai":
            break
        n += 1
        last_len = last_len or len(m["content"])
    if n == 0:
        return None
    if n >= 3:
        return "three"
    if n == 2:
        return "two"
    return "one_long" if last_len > MAX_BUBBLE_CHARS + 5 else "one_short"


def _choose_layout(history: list[dict], user_text: str, sentiment: str = "normal") -> str:
    """เลือกรูปแบบตามบริบท (ดูกติกาที่ LAYOUT_ALTERNATIVE ด้านบน)"""
    if sentiment == "distress":
        layout = "three"  # อารมณ์หนัก: ค่อยๆ ปลอบเป็นกล่องสั้นหลายกล่อง ไม่ท่วมด้วยข้อความยาว
    elif len(user_text) >= LONG_USER_MESSAGE_CHARS:
        layout = "one_long"  # เขาเล่ามาเยอะ: ตอบอบอุ่นเต็มๆ กล่องเดียว
    elif len(user_text) < SHORT_USER_MESSAGE_CHARS:
        layout = "one_short"  # พิมพ์สั้น: ตอบสั้นๆ ไม่ท่วม
    else:
        layout = "two"
    if layout == _prev_layout(history):
        layout = LAYOUT_ALTERNATIVE[layout]  # รอบก่อนตอบแบบนี้ไปแล้ว สลับเล็กน้อย
    return layout


def _short_pair(kb, used_text: str) -> list[str]:
    """สะท้อนความรู้สึก + คำถาม ที่รวมกันแล้วลงกล่องสั้น 1 กล่องได้ ถ้าไม่มีคู่ไหนพอดี ใช้แค่สะท้อนความรู้สึก (รับฟังเฉยๆ ไม่ถามต่อ)"""
    combos = [c for c in itertools.product(kb["feel"], kb["questions"]) if len(" ".join(c)) <= MAX_BUBBLE_CHARS]
    if combos:
        fresh = [c for c in combos if all(x[:25] not in used_text for x in c)]
        return list(random.choice(fresh or combos))
    return [_pick(kb["feel"], used_text, MAX_BUBBLE_CHARS)]


def _story_options(kb, st, used_text: str, n: int, max_len: int) -> list[str]:
    """v23 คำแนะนำที่ตรงกับความกังวลของผู้ใช้มาก่อน (ไม่สุ่ม) ข้ามข้อที่เคยพูดแล้ว"""
    ranked = story_mod.rank_options(kb["options"], st)
    fresh = [o for o in ranked if _said_key(o) not in used_text and len(o) <= max_len]
    pool = fresh or [o for o in ranked if len(o) <= max_len] or ranked
    return pool[:n]


def _fit_max_bubbles(bubbles: list[str], limit: int = MAX_BUBBLES) -> list[str]:
    """กันเหนียว: ถ้ายังเกิน limit กล่อง ให้ตัดกล่องตรงกลางทิ้ง (เก็บกล่องแรกกับกล่องท้ายสุดที่เป็นคำถาม)"""
    while len(bubbles) > limit:
        bubbles.pop(len(bubbles) // 2 if len(bubbles) > 2 else 0)
    return bubbles


def build_reply(history: list[dict], sentiment: str, used_replies: set | None = None, classifier=None,
                safety: dict | None = None) -> dict:
    """คืน {'reply_text', 'parts', 'topic', 'intent', 'is_crisis'} — ร่างคำตอบจากระบบเรา
    parts = รายการกล่องข้อความ (แต่ละกล่องสั้น ไม่เกิน MAX_BUBBLE_CHARS) reply_text = ทุกกล่องต่อกันคั่นบรรทัดว่าง"""
    out = _build_reply(history, sentiment, used_replies, classifier, safety)
    pieces = out["reply_parts"] if "reply_parts" in out else [out["reply_text"]]
    out.setdefault("layout", "three")
    if out["is_crisis"] or out["layout"] in ("dialogue", "story"):
        out["parts"] = [x for x in pieces if x.strip()]  # วิกฤต / คำตอบจากคลังบทสนทนา: ไม่ตัดไม่ย่อ (เขียนมาให้ลงกล่องแล้ว)
    elif out["layout"] == "one_long":
        out["parts"] = [" ".join(x.strip() for x in pieces if x.strip())]  # กล่องเดียวยาว (ไม่เกิน MAX_LONG_CHARS)
    else:
        out["parts"] = _fit_max_bubbles(split_to_bubbles(pieces), LAYOUT_LIMITS.get(out["layout"], (MAX_BUBBLES,))[0])
    out["reply_text"] = "\n\n".join(out["parts"])
    out.pop("reply_parts", None)
    return out


def _build_reply(history: list[dict], sentiment: str, used_replies: set | None = None, classifier=None,
                 safety: dict | None = None) -> dict:
    used_replies = used_replies or set()
    used_text = "\n".join(used_replies)
    last = next((m["content"] for m in reversed(history) if m["sender"] == "user"), "")
    last_l = last.lower().strip()

    if sentiment == "crisis":
        kind = (safety or {}).get("reply_kind") or "crisis"
        minor = (safety or {}).get("age_group", "unknown") != "adult"
        intent = {"crisis": "crisis", "crisis_third_party": "crisis_third_party",
                  "check_in": "check_in", "abuse": "abuse_disclosure"}.get(kind, "crisis")
        return {"reply_parts": safety_reply(kind, used_text, minor), "reply_text": "", "topic": None,
                "intent": intent, "is_crisis": True}

    advice = is_advice_request(last)
    short = len(last_l) <= 12

    # v23 ไม่ใช้คลังประโยคตายตัวแล้ว บอทอ่านเรื่องจากข้อความผู้ใช้แล้วประกอบคำตอบเอง (story.py)
    st = story_mod.understand(history)

    # เจตนาพิเศษ: ทักทาย / ขอบคุณ / ตอบสั้นไม่รู้จะพูดอะไร (ข้อความสั้น และไม่ได้ขอคำแนะนำ)
    if not advice and short:
        if any(w in last_l for w in THANKS_WORDS):
            return {"reply_text": _pick(THANKS_REPLIES, used_text), "topic": None, "intent": "thanks", "is_crisis": False}
        if any(w in last_l for w in GOODBYE_WORDS):
            return {"reply_text": _pick(GOODBYE_REPLIES, used_text), "topic": None, "intent": "goodbye", "is_crisis": False}
        if any(last_l.startswith(w.strip()) for w in GREETING_WORDS):
            return {"reply_text": _pick(GREETING_REPLIES, used_text), "topic": None, "intent": "greeting", "is_crisis": False}
        if any(w in last_l for w in EMPTY_WORDS) and not any(_keyword_score(t, last_l) for t in KNOWLEDGE):
            return {"reply_text": _pick(EMPTY_REPLIES, used_text), "topic": None, "intent": "empty", "is_crisis": False}

    # v19 คำกำกวม ("ไม่เหลือใครแล้ว" "ไม่อยากอยู่บ้านนี้แล้ว"): ถามตรงๆ ว่าหมายถึงอะไร ยังไม่ใส่เบอร์
    # ถ้าผู้ใช้ตอบรับ server.py จะเปลี่ยนเป็นโหมดวิกฤต (ดู dialogues.answered_yes_to_check)
    amb = ambiguous_check(history, used_text)
    heavy_before = any(k in " ".join(st["before"]) for k in ("โรงพยาบาล", "ป่วย", "อาการ", "ท้อง", "ดรอป", "ลำเอียง"))
    if not amb and heavy_before and "มีความคิดอยากหายไปจากทุกอย่าง" not in used_text and any(k in last_l for k in ("ไม่มีใคร", "ตัวคนเดียว")):
        amb = ["", "ผมอยากเข้าใจให้ถูกครับ ที่บอกว่าไม่มีใคร หมายถึงรู้สึกว่าไม่มีใครให้พึ่งตอนนี้ หรือมีความคิดอยากหายไปจากทุกอย่างด้วยหรือเปล่า บอกตรงๆ ได้เลย ผมรับฟังได้"]
    if amb and not amb[0]:
        amb[0] = "ต้องแบกเรื่องหนักแบบนี้ แล้วยังรู้สึกว่าไม่มีใครอยู่ข้างๆ มันโดดเดี่ยวมากจริงๆ ครับ ขอบคุณที่ยังบอกผมนะ"
    if amb and st["person_before"] and any(k in " ".join(st["before"]) for k in ("โรงพยาบาล", "ป่วย", "อาการ")):
        amb = [f"ต้องรับข่าวเรื่อง{st['person_before']} แล้วยังรู้สึกว่าไม่เหลือใครอยู่ข้างๆ เลย มันโดดเดี่ยวและหนักมากจริงๆ ครับ ขอบคุณที่ยังบอกผมนะ", amb[1]]
    if amb:
        return {"reply_parts": amb, "reply_text": "", "topic": None, "secondary_topic": None, "confidence": None,
                "topic_source": "ambiguous", "intent": "ambiguous_check", "is_crisis": False, "layout": "dialogue"}

    # v19 คุยเล่น/เรื่องดีๆ: ไม่ดึงหัวข้อปัญหามาตอบ (ข้อความต้องไม่มีคำแง่ลบ ไม่มีความทุกข์ และไม่มี keyword ปัญหาชัดๆ)
    if sentiment == "normal":
        kw_last = keyword_scores([{"sender": "user", "content": last_l}])
        strong_problem = max(kw_last.values(), default=0) >= 12 and not is_positive(last_l)  # x3 = keyword น้ำหนัก 4 ขึ้นไป
        cas = None if strong_problem else casual_reply(history, used_text)
        if cas:
            return {"reply_parts": cas, "reply_text": "", "topic": None, "secondary_topic": None, "confidence": None,
                    "topic_source": "casual", "intent": "casual", "is_crisis": False, "layout": "dialogue"}

    # จับหัวข้อ (หลังเช็กทักทาย/ขอบคุณแล้ว จะได้ไม่เรียก Gemini โดยไม่จำเป็น)
    topic_info = detect_topic_info(history, classifier)
    topic = topic_info["topic"]
    secondary = topic_info.get("secondary_topic")
    print(f"🔎 หัวข้อ={topic} รอง={secondary} (จาก {topic_info['source']}, keyword={topic_info['kw_score']}, "
          f"คะแนนรวม={topic_info['score']}, มั่นใจ={topic_info.get('confidence')}, ถามสำรวจ={topic_info.get('needs_clarify')})")
    kb = KNOWLEDGE.get(topic, GENERIC)
    all_user_text = " ".join(m["content"] for m in history if m["sender"] == "user")
    kb = {**kb, **{k: _fit_story(kb[k], all_user_text) for k in ("feel", "worth", "options", "questions") if k in kb}}
    n_user_turns = sum(1 for m in history if m["sender"] == "user")
    meta = {"topic": topic, "secondary_topic": secondary, "confidence": topic_info.get("confidence"),
            "topic_source": topic_info["source"], "is_crisis": False}

    # v16 ถามสำรวจก่อน: ข้อความแรก สั้น/กำกวม ยังไม่บอกต้นตอ -> สะท้อนความรู้สึก + ถามว่าหนักใจเพราะอะไร (ยังไม่แนะนำ)
    # ใช้แม้ผู้ใช้จะขอคำแนะนำ เพราะคำแนะนำที่ไม่รู้ต้นตอมักผิดประเด็น (เช่น แนะนำจัดตารางงานทั้งที่ทุกข์เรื่องพ่อแม่)
    # v23 ขอคำแนะนำตั้งแต่ข้อความแรก แต่เป็นเรื่องที่ต้องรู้รายละเอียดก่อน (ถูกแกล้ง ลำเอียง ป่วย ให้ดรอป) -> ถามก่อน
    if advice and n_user_turns == 1 and any(w in st["worries"] for w in ("hurt", "unfair", "illness", "decision", "conflict")):
        advice = False
    hint = story_mod.topic_hint(st)
    if hint and hint in KNOWLEDGE and topic_info["source"] != "root_cause" and hint != topic:
        topic = hint
        topic_info = {**topic_info, "topic": hint, "source": "story", "needs_clarify": False}
        kb = KNOWLEDGE[topic]
        kb = {**kb, **{k: _fit_story(kb[k], all_user_text) for k in ("feel", "worth", "options", "questions") if k in kb}}
        meta = {**meta, "topic": topic, "topic_source": "story"}
    # v24 ผู้จัดการบทสนทนา: แยกหลายเรื่อง / เข้าใจว่าปัญหาคืออะไร / ช่วยหาทางออกทีละขั้น
    mgr = manager_mod.step(history, is_advice_request, topic)
    if mgr and mgr["parts"]:
        intent = {"options": "advice", "plan": "advice", "alt": "advice", "after_plan": "advice", "advice_step": "advice",
                  "multi": "clarify", "ask_specific": "clarify"}.get(mgr["action"], "vent")
        if intent == "vent" and topic_info.get("needs_clarify") and mgr["action"] in ("reflect", "decision"):
            intent = "clarify"  # ข้อความแรกที่ยังกำกวม: คำตอบเป็นการถามสำรวจ (ไม่แนะนำ) ติดป้ายเหมือนเดิม
        return {**meta, "reply_parts": mgr["parts"], "reply_text": "", "intent": intent, "layout": "story",
                "roles": None, "safety": "", "plan": {"action": mgr["action"], **mgr["state"]}}
    task_topic = topic in TASK_TOPICS
    s_reflect = story_mod.reflect(st, topic, used_text) or story_mod.generic_reflect(st, topic)
    s_question = story_mod.question(st, topic, used_text, task_topic)
    if topic_info.get("needs_clarify"):
        parts = _clarify_parts(topic, last, used_text)
        if s_reflect:
            parts[0] = s_reflect  # v23 สะท้อนด้วยคำของผู้ใช้แทนประโยคกลาง
        if s_question:
            parts[1] = s_question
        return {**meta, "reply_parts": parts, "reply_text": "", "intent": "clarify", "layout": "two",
                "roles": ["feel", "question"], "safety": ""}

    # v16 บอกต้นตอแล้ว (คน + แรงกดดัน) และมีเรื่องหน้าฉาก -> ประโยคแรกเชื่อมทั้งสองเรื่องเข้าด้วยกัน
    bridge = ""
    root = topic_info.get("root")
    if topic_info["source"] in ("root_cause", "context_shift") and secondary in TASK_TOPICS and topic in ROOT_BRIDGE:
        all_user = " ".join(m["content"] for m in history if m["sender"] == "user")
        person = (root or {}).get("person", "คนรอบข้าง")
        bridge = ROOT_BRIDGE[topic].format(surface=_surface_word(secondary, all_user), person=person)
        if len(bridge) > MAX_BUBBLE_CHARS or bridge[:25] in used_text:
            bridge = ""

    # v18 อ้างเรื่องที่คุยกันก่อนหน้าแบบเบาๆ: เฉพาะตอนผู้ใช้พิมพ์แค่ความรู้สึก (เช่น "เหนื่อยมาก ไม่ไหวแล้ว")
    # ต่อจากเรื่องเดิม และใช้แค่ครั้งเดียวต่อบทสนทนา ที่เหลือตอบแบบเดิมทุกอย่าง (ประโยคของหัวข้อนั้นๆ)
    if not bridge and not advice and topic_info["source"] == "context" and _is_pure_feeling(last):
        about = _recent_story(history[:-1])
        if about and not any(r.split("{about}")[1][:15] in used_text for r in RECALL_FEEL):
            cand = _pick(RECALL_FEEL, used_text).format(about=about)
            if len(cand) <= MAX_BUBBLE_CHARS:
                bridge = cand

    # ทุกท่อนเลือกให้ "ลงกล่องเดียว" (ไม่ยาวเกิน MAX_BUBBLE_CHARS) แล้วใช้ได้สูงสุด 3 กล่อง: [กล่อง 1][กล่อง 2][คำถาม]
    prev_replies = max(n_user_turns - 1, 0)  # จำนวนครั้งที่บอทเคยตอบมาแล้ว (ไม่นับเป็นกล่อง)
    question = _pick(kb["questions"], used_text, MAX_BUBBLE_CHARS)
    safety = kb.get("safety", "")
    if safety and (safety[:25] in used_text or len(safety) > MAX_BUBBLE_CHARS):
        safety = ""  # เคยเตือนไปแล้ว (หรือยาวเกินกล่อง) ไม่พูดซ้ำ

    roles = None  # หน้าที่ของแต่ละกล่อง (ใช้บอก Gemini ตอนให้คิดคำแนะนำเอง)
    if advice:
        # ขอคำแนะนำ: ถ้าเป็นข้อความแรกของบทสนทนา สะท้อนความรู้สึกก่อน 1 กล่อง แล้วให้คำแนะนำ 1 ข้อ
        # ถ้าคุยกันมาแล้ว ให้คำแนะนำ 2 ข้อทันที (ข้อที่ 2 อาจเป็นคำเตือนความปลอดภัยถ้ามีและยังไม่เคยพูด)
        # คำแนะนำเลือกข้อที่สั้นพอจะลงกล่องเดียว (เผื่อคำนำหน้า 'อย่างแรก ' ประมาณ 12 ตัวอักษร)
        opt_limit = MAX_BUBBLE_CHARS - 13
        usable = [o for o in kb["options"] if len(o) <= opt_limit] or kb["options"]
        out_of_options = prev_replies > 0 and all(_said_key(o) in used_text for o in usable)
        if out_of_options:
            # ทางเลือกของหัวข้อนี้พูดครบแล้ว: ไม่วนพูดข้อเดิม เปลี่ยนเป็นชวนเลือกลองทีละข้อ / ปรึกษาคนอื่น
            parts = [_pick(OUT_OF_OPTIONS["feel"], used_text, MAX_BUBBLE_CHARS),
                     _pick(OUT_OF_OPTIONS["advice"], used_text, MAX_BUBBLE_CHARS),
                     _pick(OUT_OF_OPTIONS["questions"], used_text, MAX_BUBBLE_CHARS)]
            roles = ["feel", "advice", "question"]
        elif prev_replies == 0 or bridge:
            feel = bridge or s_reflect or _pick(kb["feel"], used_text, MAX_BUBBLE_CHARS)
            parts = [feel] + _option_pieces(_story_options(kb, st, used_text, 1, opt_limit)) + [question]
            roles = ["feel", "advice", "question"]
        else:
            opts = _option_pieces(_story_options(kb, st, used_text, 2, opt_limit))
            intro = story_mod.advice_intro(st)
            if intro and len(intro) + 1 + len(opts[0]) <= MAX_LONG_CHARS:
                opts[0] = intro + " " + opts[0]
            roles = ["advice", "advice", "question"]
            if safety:
                opts = opts[:1] + [safety]
                roles = ["advice", "safety", "question"]
            parts = opts + [question]
        intent = "advice"
        layout = "story" if s_reflect or st["context_worries"] else "three"
    elif s_reflect or (topic is None and not bridge):
        # v23 ระบาย: [สะท้อนด้วยคำของผู้ใช้] + (กล่องปกป้องคุณค่า ถ้าเรื่องหนัก และเป็นครั้งแรก) + [คำถามตรงจุดที่ยังไม่รู้]
        if not s_reflect:
            topic_word = SURFACE_NAME.get(topic) if topic else None
            parts = [story_mod.unsure(st, topic_word, used_text)]
        else:
            first = bridge or s_reflect
            q = s_question or _pick(kb["questions"], used_text, MAX_BUBBLE_CHARS)
            worth = story_mod.worth(st, used_text)
            parts = [first] + ([worth] if worth else []) + [q]
        intent = "vent"
        layout = "story"
    else:
        # ระบาย: เลือกรูปแบบตามบริบท (ดู _choose_layout) แล้วประกอบเนื้อหาตามรูปแบบนั้น
        layout = _choose_layout(history, last, sentiment)
        feel = bridge or _pick(kb["feel"], used_text, MAX_BUBBLE_CHARS)
        if bridge and layout in ("one_long", "one_short"):
            layout = "three"  # ต้องการกล่องเชื่อมต้นตอ
        # v16: ตอนระบาย "ไม่" ใส่คำแนะนำ/ทางเลือก จนกว่าผู้ใช้จะขอ (ใช้คำถามแทน)
        option_line = question
        one_box = _try_one_box(kb, used_text, allow_options=False) if layout == "one_long" else None
        if layout == "one_long" and not one_box:
            layout = "three"
        if layout == "one_long":
            parts = [one_box]
        elif layout == "one_short":
            pair = _short_pair(kb, used_text)
            fixed = _avoid_repeats(pair, kb, used_text)
            parts = [" ".join(fixed if len(" ".join(fixed)) <= MAX_BUBBLE_CHARS else pair)]
        elif layout == "two":
            # 2 กล่อง: [สะท้อนความรู้สึก] + [ทางเลือกเล็กๆ หรือ คำถาม] สุ่มอย่างใดอย่างหนึ่ง
            parts = [feel, question]
        else:
            # 3 กล่อง: [สะท้อนความรู้สึก][ปกป้องคุณค่า/ทางเลือก/คำเตือน หมุนเวียน][คำถาม]
            worth = _pick(kb["worth"], used_text, MAX_BUBBLE_CHARS)
            candidates = {"worth": worth, "safety": safety}
            order = ["worth", "safety"] if prev_replies == 0 else ["safety", "worth"]
            middle = next((candidates[k] for k in order if candidates[k] and candidates[k][:25] not in used_text), worth)
            parts = [feel, middle, question]
        if layout in ("two", "three"):
            parts = _avoid_repeats(parts, kb, used_text)
        intent = "vent"

    return {**meta, "reply_parts": parts, "reply_text": "", "intent": intent, "layout": layout,
            "roles": roles, "safety": safety}
