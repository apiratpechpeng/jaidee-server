def split_to_bubbles(pieces: list[str], max_chars: int = MAX_BUBBLE_CHARS) -> list[str]:
    """รับท่อนข้อความหลายท่อน แล้วจัดเป็น "กล่องข้อความ" ที่แต่ละกล่องไม่เกิน max_chars
    - แต่ละท่อน (สะท้อน/ปกป้อง/ทางเลือก/คำถาม) อยู่คนละกล่อง ไม่เอามารวมกัน
    - ท่อนที่ยาวเกินจะถูกตัดตามช่องว่าง (ช่องว่างในข้อความไทยของเราคือรอยต่อวลี/ประโยค) จะไม่ตัดกลางคำ"""
    chunks = []
    for piece in pieces:
        piece = piece.strip()
        if not piece:
            continue
        if len(piece) <= max_chars:
            chunks.append(piece)
            continue
        # ตัดให้ "สมดุล" (ครึ่งๆ กัน) จะได้ไม่เหลือเศษสั้นๆ โดดเดี่ยวท้ายข้อความ
        n_parts = -(-len(piece) // max_chars)
        target = len(piece) / n_parts
        cur = ""
        for word in piece.split(" "):
            if cur and len(cur) + 1 + len(word) > max_chars or (cur and len(cur) >= target):
                chunks.append(cur)
                cur = word
            else:
                cur = f"{cur} {word}" if cur else word
        if cur:
            chunks.append(cur)
    bubbles = chunks  # ไม่รวมท่อนต่างหน้าที่เข้าด้วยกัน (เช่น คำถามต้องอยู่กล่องของตัวเอง)
    return bubbles


