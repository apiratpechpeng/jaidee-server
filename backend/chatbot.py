def _is_negated(text: str, start: int) -> bool:
    """keyword ที่ตำแหน่ง start มีคำปฏิเสธอยู่ติดหน้าไหม (ยอมให้มีช่องว่างคั่นได้ 1 ช่อง)"""
    before = text[max(0, start - 8):start].rstrip()
    return any(before.endswith(w) for w in NEGATION_WORDS)


def _keyword_score(topic: str, text: str) -> int:
    """รวมน้ำหนักของ keyword ของหัวข้อนี้ที่เจอในข้อความ (ข้าม keyword ที่ถูกปฏิเสธ)"""
    total = 0
    check_neg = topic not in NEGATION_EXEMPT_TOPICS
    for kw, w in KNOWLEDGE[topic]["kw"].items():
        pos = text.find(kw)
        if pos < 0:
            continue
        if check_neg and not kw.startswith("ไม่"):
            # นับเฉพาะเมื่อมีอย่างน้อย 1 ครั้งที่ไม่ถูกปฏิเสธ
            while pos >= 0 and _is_negated(text, pos):
                pos = text.find(kw, pos + 1)
            if pos < 0:
                continue
        total += w
    return total


def keyword_scores(history: list[dict]) -> dict[str, int]:
    """ด่านที่ 1: นับคะแนน keyword ข้อความล่าสุดน้ำหนัก x3, ข้อความผู้ใช้ก่อนหน้า (สูงสุด 3 ข้อความ) x1"""
    user_msgs = [m["content"].lower() for m in history if m["sender"] == "user"]
    if not user_msgs:
        return {}
    last, previous = user_msgs[-1], user_msgs[-4:-1]
    scores = {}
    for topic in KNOWLEDGE:
        s = _keyword_score(topic, last) * 3
        for prev in previous:
            s += _keyword_score(topic, prev)
        if s:
            scores[topic] = s
    return scores


def nlp_scores(history: list[dict]) -> dict[str, float]:
    """ด่านที่ 2: เทียบความคล้ายของ "ข้อความล่าสุด" กับประโยคตัวอย่าง (nlp.py)
    ไม่เอาข้อความก่อนหน้ามาต่อกัน เพราะทำให้เดาหัวข้อมั่ว (ความต่อเนื่องของเรื่องให้ STICKY_BONUS ดูแลแทน)
    ข้อความสั้นลดน้ำหนักลงตามความยาว (ดู NLP_FULL_LENGTH)"""
    from .nlp import content_length, get_matcher
    user_msgs = [m["content"] for m in history if m["sender"] == "user"]
    if not user_msgs:
        return {}
    last = user_msgs[-1]
    n = content_length(last)
    if n < NLP_MIN_CONTENT:
        return {}
    scores = get_matcher().scores(last)
    if n < NLP_FULL_LENGTH:
        scores = {t: v * n / NLP_FULL_LENGTH for t, v in scores.items()}
    return scores


def _ranked(scores: dict) -> list[tuple[str, float]]:
    return sorted(scores.items(), key=lambda kv: kv[1], reverse=True)


# v18 ความเร็ว: หัวข้อของข้อความเก่าๆ ไม่เปลี่ยนแล้ว เก็บผลไว้ใช้ซ้ำ ไม่ต้องคิดใหม่ทั้งบทสนทนาทุกครั้ง
_TOPIC_MEMO: dict = {}
_TOPIC_MEMO_MAX = 5000


def _cached_topic(prefix: list[dict], prev_topic):
    key = (tuple(m["content"] for m in prefix if m["sender"] == "user"), prev_topic)
    if key not in _TOPIC_MEMO:
        if len(_TOPIC_MEMO) > _TOPIC_MEMO_MAX:
            _TOPIC_MEMO.clear()
        _TOPIC_MEMO[key] = _detect_core(prefix, None, True, prev_topic)["topic"]
    return _TOPIC_MEMO[key]


# v18 ข้อความที่มี "แต่ความรู้สึก" ล้วนๆ (เช่น "เหนื่อยมาก ไม่ไหวแล้ว") = ความรู้สึกต่อเรื่องเดิม ไม่ใช่เรื่องใหม่
# ใช้แคบๆ เฉพาะข้อความที่ตัดคำพวกนี้ออกแล้วแทบไม่เหลืออะไร ถ้ามีเรื่องราวใหม่ปนมา ระบบจะจับหัวข้อตามปกติ (เหมือน v16)
PURE_FEELING_WORDS = [
    "เหนื่อยมาก", "เหนื่อยใจ", "เหนื่อย", "ไม่ไหวแล้ว", "ไม่ไหว", "ทนไม่ไหว", "เครียดมาก", "เครียด", "ร้องไห้", "เศร้ามาก",
    "เศร้า", "ท้อมาก", "ท้อ", "หมดแรง", "แย่มาก", "แย่", "หนักใจ", "จริงๆ", "มากๆ", "มาก", "เลย", "แล้ว", "ด้วย", "อีก",
    "ก็", "นะ", "อะ", "อ่ะ", "จัง", "ครับ", "ค่ะ", "คะ",
]
_PURE_SORTED = sorted(PURE_FEELING_WORDS, key=len, reverse=True)


def _is_pure_feeling(text: str) -> bool:
    from .nlp import content_length
    if content_length(text) == 0:
        return False
    t = text
    for w in _PURE_SORTED:
        t = t.replace(w, " ")
    return content_length(t) <= 2


def _detect_core(history: list[dict], classifier=None, use_nlp: bool = True, _prev="auto") -> dict:
    """(ภายใน) จับหัวข้อแบบ 3 ด่าน คืน {'topic', 'source', 'kw_score', 'score'}
      ด่าน 1 keyword: ถ้าชัดมากใช้เลย (source = keyword)
      ด่าน 2 รวมคะแนน keyword + NLP (source = keyword+nlp)
      ด่าน 3 ถ้ายังไม่มั่นใจ และมี Gemini -> ให้ Gemini เลือกจากหัวข้อที่คะแนนสูงสุด 4 อันดับ (source = gemini)
    classifier = ฟังก์ชันของ Gemini (ส่งมาจาก ai.py) รับ (history, รายชื่อหัวข้อที่น่าจะเป็น, หัวข้อที่กำลังคุยอยู่) คืนชื่อหัวข้อ / "none" / None
    use_nlp=False = แบบเดิม (keyword อย่างเดียว เกณฑ์ 4 คะแนน) ใช้เทียบในชุดทดสอบ"""
    kw = keyword_scores(history)
    kw_rank = _ranked(kw)
    kw_topic, kw_best = kw_rank[0] if kw_rank else (None, 0)
    kw_second = kw_rank[1][1] if len(kw_rank) > 1 else 0
    info = {"topic": None, "source": "none", "kw_score": kw_best, "score": 0.0}

    if not use_nlp:
        return {**info, "topic": kw_topic, "source": "keyword"} if kw_best >= 4 else info

    # หัวข้อที่กำลังคุยอยู่ก่อนข้อความนี้: ไล่คิดทีละข้อความของผู้ใช้ตั้งแต่ต้น แล้วส่งต่อหัวข้อไปข้อความถัดไป (ไม่เรียก Gemini)
    prev_topic = _prev
    if _prev == "auto":
        prev_topic = None
        user_idx = [i for i, m in enumerate(history) if m["sender"] == "user"]
        for idx in user_idx[:-1]:
            prev_topic = _cached_topic(history[:idx + 1], prev_topic)
    info["prev_topic"] = prev_topic

    nlp = nlp_scores(history)
    last_text = next(m["content"].lower() for m in reversed(history) if m["sender"] == "user")
    info["_kw"], info["_nlp"] = kw, nlp

    # v16 ต้นตอความกดดัน: ข้อความล่าสุดมี "คน + แรงกดดัน" (เช่น พ่อแม่คาดหวัง) -> หัวข้อหลักคือเรื่องคน
    # เรื่องที่หยิบมาเล่า (โครงงาน สอบ) เป็นหัวข้อรองแทน และสลับหัวข้อทันทีแม้กำลังคุยเรื่องอื่นอยู่
    prev_texts = [m["content"].lower() for m in history if m["sender"] == "user"][:-1]
    root = detect_root_cause(last_text, prev_texts[-1] if prev_texts else "")  # v22 คนอยู่ในข้อความก่อนหน้าได้
    if root and root["topic"] in KNOWLEDGE:
        return {**info, "topic": root["topic"], "source": "root_cause", "root": root}

    # ด่านที่ 1: keyword ชัดมาก (ย้ายมาไว้หลังการตรวจต้นตอใน v16 ไม่อย่างนั้นคำว่า "เกรด" "สอบ" จะชนะต้นตอเสมอ)
    if kw_best >= KW_SURE and kw_best - kw_second >= KW_MARGIN and not prev_topic:
        return {**info, "topic": kw_topic, "source": "keyword"}

    # v18: แค่ความรู้สึกล้วนๆ ต่อเรื่องเดิม -> คุยเรื่องเดิมต่อ
    if prev_topic and _is_pure_feeling(last_text):
        return {**info, "topic": prev_topic, "source": "context"}

    # v16 เปลี่ยนเรื่องตามบริบทใหม่: ข้อความล่าสุด "ข้อความเดียว" มี keyword ของหัวข้ออื่นชัดกว่าหัวข้อเดิม -> สลับเลย
    # (เดิมโบนัสหัวข้อเดิมทำให้ติดหัวข้อแรก ถ้าไม่มี Gemini ช่วยตัดสิน)
    if prev_topic:
        last_kw = {t: _keyword_score(t, last_text) for t in KNOWLEDGE}
        cand = max(last_kw, key=last_kw.get)
        if cand != prev_topic and last_kw[cand] >= SWITCH_KW_MIN and last_kw[cand] > last_kw.get(prev_topic, 0):
            return {**info, "topic": cand, "source": "context_shift"}

    # ข้อความล่าสุดไม่มีเนื้อหาเรื่องราวและไม่มี keyword (เช่น "อืม" "แล้วทำไงดี") -> คุยเรื่องเดิมต่อ
    last_has_keyword = any(_keyword_score(t, last_text) for t in KNOWLEDGE)
    if not last_has_keyword and (not nlp or any(w in last_text for w in SMALL_TALK)):
        return {**info, "topic": prev_topic, "source": "context" if prev_topic else "none"}

    # ด่านที่ 2: รวมคะแนน keyword + NLP + โบนัสหัวข้อเดิม
    combined = {t: nlp.get(t, 0.0) + KW_WEIGHT * kw.get(t, 0) for t in set(nlp) | set(kw)}
    if prev_topic:
        combined[prev_topic] = combined.get(prev_topic, 0.0) + STICKY_BONUS
    rank = _ranked(combined)
    info["_combined"] = combined
    best_topic, best = rank[0] if rank else (None, 0.0)
    gap = best - (rank[1][1] if len(rank) > 1 else 0.0)
    info["score"] = round(best, 3)
    sure = best >= SURE_SCORE and gap >= SURE_GAP

    # ด่านที่ 3: ไม่มั่นใจ -> ถาม Gemini
    continuing = bool(prev_topic) and best_topic == prev_topic  # ยังคุยเรื่องเดิมอยู่
    # ถ้ายังคุยเรื่องเดิม แต่มีหัวข้อใหม่ที่ข้อความนี้ชี้ไปหาพอสมควร (CHALLENGER_SCORE) ให้ Gemini ช่วยตัดสินว่าเปลี่ยนเรื่องไหม
    challenger = max((nlp.get(t, 0.0) + KW_WEIGHT * kw.get(t, 0) for t in set(nlp) | set(kw) if t != prev_topic), default=0.0)
    may_switch = continuing and challenger >= CHALLENGER_SCORE
    if (not sure or may_switch) and classifier and rank:
        try:
            picked = classifier(history, [t for t, _ in rank[:4]], prev_topic)
        except Exception as err:  # Gemini พังก็ไม่เป็นไร ใช้ผลจากในเครื่องต่อ
            print(f"Gemini จับหัวข้อไม่สำเร็จ ใช้ผลจากในเครื่อง: {err}")
            picked = None
        if picked == "none":
            return {**info, "topic": prev_topic, "source": "gemini"}  # ไม่ใช่เรื่องใหม่ -> คุยเรื่องเดิมต่อ (ถ้ามี)
        if picked in KNOWLEDGE:
            return {**info, "topic": picked, "source": "gemini"}

    own_evidence = bool(nlp.get(best_topic)) or bool(kw.get(best_topic))
    if continuing:
        # หัวข้อเดิมยังนำอยู่ (มีโบนัสหัวข้อเดิมช่วย) -> คุยเรื่องเดิมต่อ ต่อให้ข้อความนี้ไม่ค่อยมีเนื้อหา
        return {**info, "topic": best_topic, "source": "keyword+nlp" if best >= MIN_SCORE and own_evidence else "context"}
    # NLP เดาอ่อนๆ อย่างเดียว (ไม่มี keyword ของหัวข้อนั้นเลย และคะแนนต่ำกว่า NLP_ONLY_MIN)
    # -> ไม่เดาหัวข้อ ตอบแบบรับฟังทั่วไปแล้วถามต่อ ดีกว่าตอบผิดเรื่อง (เช่น "เครียดมากเลย" แล้วไปตอบเรื่องค่าเทอม)
    weak_guess = not kw.get(best_topic) and best < NLP_ONLY_MIN
    if best >= MIN_SCORE and not weak_guess:
        return {**info, "topic": best_topic, "source": "keyword+nlp"}
    if prev_topic:
        return {**info, "topic": prev_topic, "source": "context"}
    if kw_best >= KW_MIN:
        return {**info, "topic": kw_topic, "source": "keyword-weak"}
    return info


