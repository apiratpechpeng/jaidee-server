def _advise_with_gemini(history, draft: dict) -> list[str]:
    """ให้ Gemini "คิดคำแนะนำ" เอง ตามเรื่องที่ผู้ใช้เล่า โดยระบบเราส่งแนวทางให้
      - หัวข้อที่ระบบจับได้ + ตัวอย่างสถานการณ์ (scenarios.py)
      - คำแนะนำในคลังของหัวข้อนั้น (KNOWLEDGE) เป็นแนวทาง ไม่ต้องลอกตรงๆ
      - โครงกล่องที่ต้องตอบ (roles) และเบอร์ที่อนุญาต
    แล้วตรวจผลด้วย check_generated_reply ถ้าไม่ผ่านคืน [] (ผู้เรียกจะใช้คำแนะนำจากคลังแทน)"""
    topic = draft.get("topic")
    kb = KNOWLEDGE.get(topic)
    roles = draft.get("roles") or ["advice", "advice", "question"]
    safety = draft.get("safety") or ""

    guide_lines = []
    guide_lines.append(_topic_context(draft).strip())
    for title, example in examples_for(topic):
        guide_lines.append(f"ตัวอย่างเรื่องที่ผู้ใช้หัวข้อนี้มักเล่า: \"{example}\"")
    for u, b in dialogue_examples(history):
        guide_lines.append(f"ตัวอย่างคำตอบที่ผู้พัฒนาอนุมัติ (ดูน้ำเสียงและความยาว ไม่ต้องลอก): ผู้ใช้: \"{u}\" -> บอท: \"{b}\"")
    if kb:
        guide_lines.append("แนวทางคำแนะนำจากคลังของเรา (ใช้เป็นแนวทาง เลือก ปรับ หรือคิดใหม่ให้ตรงกับรายละเอียดที่ผู้ใช้เล่า):")
        guide_lines += [f"- {o}" for o in kb["options"]]
    hotline_lines = [f"- {num}: {desc}" for num, desc in ALLOWED_HOTLINES.items()]
    box_lines = [f"กล่องที่ {i + 1}: " + _ROLE_TEXT[r].format(safety=safety) for i, r in enumerate(roles)]

    instruction = (
        "\n\n[คำสั่งระบบ — ผู้ใช้ไม่เห็นข้อความนี้]\n"
        "ผู้ใช้กำลังขอคำแนะนำ ให้คุณคิดคำแนะนำเบื้องต้นที่ทำได้จริงและตรงกับเรื่องที่เขาเล่ามาในบทสนทนา "
        "(อ้างถึงรายละเอียดที่เขาเล่า ไม่ใช่คำแนะนำกว้างๆ) และห้ามซ้ำกับคำแนะนำที่บอทเคยให้ไปแล้วในบทสนทนานี้\n"
        + "\n".join(guide_lines) + "\n\n"
        "ข้อห้าม: ห้ามวินิจฉัยโรค ห้ามแนะนำยาหรือการใช้ยา ห้ามปัดตกความรู้สึก (เช่น อย่าคิดมาก ปล่อยวางเถอะ) "
        "ห้ามแนะนำสิ่งที่ผิดกฎหมายหรืออันตราย ถ้าจำเป็นต้องให้ติดต่อหน่วยงาน ใช้ได้เฉพาะเบอร์ในรายการนี้เท่านั้น ห้ามแต่งเบอร์อื่น:\n"
        + "\n".join(hotline_lines) + "\n\n"
        f"รูปแบบคำตอบ: แบ่งเป็น {len(roles)} กล่อง คั่นแต่ละกล่องด้วยบรรทัดว่าง 1 บรรทัด "
        f"แต่ละกล่องไม่เกิน {MAX_BUBBLE_CHARS} ตัวอักษร (ประมาณ 1-2 ประโยค) ห้ามใช้หัวข้อ ตัวหนา หรือเลขข้อ "
        "ภาษาพูดอบอุ่นแบบเพื่อน ลงท้ายด้วย 'ครับ'\n"
        + "\n".join(box_lines) + "\n"
        "ตอบเฉพาะข้อความคำตอบสุดท้ายเท่านั้น"
    )

    turns = []
    for m in history[-10:]:
        role = "user" if m["sender"] == "user" else "model"
        if turns and turns[-1]["role"] == role:
            turns[-1]["parts"][0]["text"] += "\n" + m["content"]
        else:
            turns.append({"role": role, "parts": [{"text": m["content"]}]})
    if not turns or turns[-1]["role"] != "user":
        turns.append({"role": "user", "parts": [{"text": ""}]})
    turns[-1]["parts"][0]["text"] += instruction

    text = _call_gemini(_CHAT_SYSTEM_PROMPT, turns, max_tokens=4096, temperature=0.7).strip()
    # เบอร์ที่ "ต้องมี" คือเบอร์ในคำเตือนความปลอดภัยที่สั่งให้ใส่ (ส่วนเบอร์ในคลังเป็นแค่แนวทาง ไม่บังคับ)
    required = safety if "safety" in roles else ""
    bubbles, reason = check_generated_reply(text, required, max_boxes=len(roles))
    if reason:
        print(f"ตรวจคำแนะนำจาก Gemini ไม่ผ่าน ({reason})")
        if reason.startswith(_SAFETY_REASONS):
            _mark_safety_block(reason)
    return bubbles



