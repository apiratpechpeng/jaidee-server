def _phone_like_numbers(text: str) -> set[str]:
    """ดึงตัวเลขที่หน้าตาเหมือนเบอร์โทรออกมา (3-4 หลักโดดๆ หรือเบอร์ 0x-xxx-xxxx)"""
    found = set()
    for m in re.finditer(r"0\d{1,2}-?\d{3}-?\d{3,4}", text):
        found.add(m.group(0).replace("-", ""))
    cleaned = re.sub(r"0\d{1,2}-?\d{3}-?\d{3,4}", " ", text)
    for m in re.finditer(r"(?<![\d,.\-])(\d{3,4})(?![\d,.\-])", cleaned):
        num = m.group(1)
        is_year = len(num) == 4 and num[:2] in ("25", "20")  # เช่น 2569 / 2026 คือปี ไม่ใช่เบอร์
        if not is_year and not re.match(_UNIT_AFTER_NUMBER, cleaned[m.end():]):
            found.add(num)
    return found


def check_generated_reply(text: str, draft_text: str, max_boxes: int) -> tuple[list[str], str]:
    """ตรวจคำตอบที่ AI แต่งเอง คืน (กล่องข้อความ, "") ถ้าผ่าน หรือ ([], เหตุผล) ถ้าไม่ผ่าน
    draft_text = ข้อความที่มีเบอร์ซึ่ง "ต้อง" อยู่ในคำตอบด้วย (เช่น คำเตือนความปลอดภัย)"""
    if not text or len(text) < 40:
        return [], "สั้นเกินไปหรือว่าง"
    for phrase in FORBIDDEN_PHRASES:
        if phrase in text:
            return [], f"มีคำต้องห้าม: {phrase}"
    unknown = _phone_like_numbers(text) - _ALLOWED_DIGITS
    if unknown:
        return [], f"มีเบอร์ที่ไม่ได้อนุญาต: {sorted(unknown)}"
    missing = (_phone_like_numbers(draft_text) & _ALLOWED_DIGITS) - _phone_like_numbers(text)
    if missing:
        return [], f"ทำเบอร์สายด่วนในร่างหาย: {sorted(missing)}"
    bubbles = split_to_bubbles([t for t in re.split(r"\n\s*\n", text) if t.strip()])
    if not 1 <= len(bubbles) <= max_boxes:
        return [], f"จำนวนกล่อง {len(bubbles)} เกิน {max_boxes}"
    return bubbles, ""


