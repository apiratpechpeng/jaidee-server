def _fewshot(plan: dict) -> str:
    """ตัวอย่างวิธีตอบของเรื่องที่กำลังคุย (ไม่เกิน 2 ตัวอย่าง) — ใช้เป็นแนวทาง ไม่ใช่ให้ลอก"""
    kinds = plan.get("areas", {}).get(plan.get("active") or "", {}).get("kinds", [])
    keys = []
    for k in (["cyber"] if "cyber" in kinds else []) + (["appearance"] if "appearance" in kinds and "hurt" in kinds else []) + list(kinds):
        key = _FEWSHOT_OF.get(k)
        if key and key not in keys:
            keys.append(key)
    if not keys:
        return ""
    ex = "\n\n".join(FEWSHOT_V25[k] for k in keys[:2])
    return f"ตัวอย่างวิธีตอบเรื่องแนวนี้ (ใช้เป็นแนวทาง ห้ามลอกประโยค ต้องใช้รายละเอียดของผู้ใช้คนนี้เท่านั้น):\n{ex}\n"


