    bubbles, why = check_generated_reply(text, draft["reply_text"], 3)
    if not bubbles:
        if why.startswith(_SAFETY_REASONS):
            _mark_safety_block(why)
        return []
    if len(" ".join(bubbles)) > 650:
        return []
    from .story import PEOPLE
    said = " ".join(m["content"] for m in history if m["sender"] == "user")
    joined = " ".join(bubbles)
