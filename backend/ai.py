# ด่านเสริมของการตรวจภาวะวิกฤต: Gemini อ่านข้อความ (ยกระดับได้อย่างเดียว ดู crisis.assess)
# เรียกเฉพาะเมื่อ keyword + NLP ไม่พบ และข้อความมีเนื้อหาพอ (เปิด/ปิดด้วย GEMINI_CRISIS_CHECK ใน .env)
# ---------------------------------------------------------------------
_CRISIS_CACHE: dict[str, str | None] = {}


def gemini_crisis_enabled() -> bool:
    return bool(_api_key()) and os.environ.get("GEMINI_CRISIS_CHECK", "1") != "0"


def classify_crisis_with_gemini(text: str) -> str | None:
    """คืน 'HIGH' / 'MODERATE' / 'NONE' หรือ None ถ้าเรียกไม่สำเร็จ"""
    if not text or len(text.strip()) < 8:
        return None
    if text in _CRISIS_CACHE:
        return _CRISIS_CACHE[text]
    system = (
        "คุณเป็นตัวคัดกรองความเสี่ยงการทำร้ายตนเองในข้อความภาษาไทยของวัยรุ่น ตอบเป็น JSON บรรทัดเดียวเท่านั้น\n"
        "HIGH = ผู้เขียนพูดถึงความตั้งใจ แผน หรือวิธีจบชีวิต/ทำร้ายตนเอง\n"
        "MODERATE = ผู้เขียนมีความคิดอยากหายไป ไม่อยากตื่น รู้สึกเป็นภาระ หมดหวัง ไม่มีเหตุผลที่จะอยู่ (แม้พูดอ้อม)\n"
        "NONE = เครียดหรือเศร้าทั่วไป ใช้คำว่าตายแบบภาษาพูด หรือพูดถึงข่าว/นิยาย/คนอื่นโดยไม่เกี่ยวกับตัวผู้เขียน\n"
        "ถ้าไม่แน่ใจระหว่าง MODERATE กับ NONE ให้ตอบ MODERATE\n"
        'รูปแบบ: {"level": "HIGH"} หรือ {"level": "MODERATE"} หรือ {"level": "NONE"}'
    )
    try:
        raw = _call_gemini(system, [{"role": "user", "parts": [{"text": text}]}], 30, temperature=0.0, timeout=8)
        m = re.search(r'"level"\s*:\s*"(HIGH|MODERATE|NONE)"', raw)
        level = m.group(1) if m else None
    except Exception as err:  # v29
        print(f"Gemini ตรวจวิกฤตไม่สำเร็จ ใช้ผล keyword + NLP อย่างเดียว: {err}")
        level = None
    _CRISIS_CACHE[text] = level
    return level
