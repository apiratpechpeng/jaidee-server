def reply_to_chat(history: list[dict], sentiment: str, safety: dict | None = None) -> dict:
    """ระบบเราเป็นตัวหลัก: chatbot.build_reply() ร่างคำตอบจากคลังความรู้ และคุมรูปแบบ/ความยาว/ความปลอดภัย
    - ขอคำแนะนำ ("ควรทำไงดี"): ให้ Gemini เป็นคน "คิดคำแนะนำ" ให้ตรงกับเรื่องที่ผู้ใช้เล่า โดยดูคลังของเราเป็นแนวทาง
    - ระบาย: Gemini แค่เรียบเรียงร่างของเราให้เป็นธรรมชาติ
    - ภาวะวิกฤต: ใช้ข้อความตายตัวที่ปลอดภัยเสมอ ไม่ส่งให้ AI แต่ง
    ถ้าไม่มี key, Gemini พัง หรือคำตอบของ Gemini ไม่ผ่านการตรวจ -> ใช้ร่างของระบบเราแทน
    ผลลัพธ์มีข้อมูลประกอบ (intent, topic, safety_blocked) ไว้ทำ analytics ด้วย"""
    _guard.blocked = False
    used_replies = {m["content"] for m in history if m["sender"] == "ai"}
    # ด่านที่ 3 ของการจับหัวข้อ: ส่งตัวช่วยของ Gemini ไปให้ chatbot ใช้ "เฉพาะตอนที่ keyword + NLP ไม่มั่นใจ"
    classifier = classify_topic_with_gemini if _api_key() and sentiment != "crisis" else None
    draft = build_reply(history, sentiment, used_replies, classifier, safety)
    meta = {"layout": draft["layout"], "intent": draft["intent"], "topic": draft.get("topic"),
            "secondary_topic": draft.get("secondary_topic"), "confidence": draft.get("confidence"),
            "topic_source": draft.get("topic_source", "none"), "dialogue_id": draft.get("dialogue_id")}
    result = {**meta, "reply_text": draft["reply_text"], "reply_parts": draft["parts"], "model_name": "rule-based", "model_version": "v29"}

    def finish(out):
        out["safety_blocked"] = bool(getattr(_guard, "blocked", False))
        return out

    # v19 คำตอบจากคลังบทสนทนา / คุยเล่น / ถามเช็กคำกำกวม: ใช้ตามที่เขียนไว้ ไม่ให้ Gemini แต่งใหม่
    if draft["is_crisis"] or draft.get("layout") == "dialogue" or not _api_key():
        return finish(result)
    try:
        # v24 Gemini เป็นตัวหลัก: เขียนคำตอบเองทั้งหมด โดยทำตาม "ขั้นของบทสนทนา" ที่ manager.py คิดไว้
        # (เรื่องที่ผู้ใช้เล่า / กำลังคุยเรื่องไหน / ต้องทำอะไรในรอบนี้) ไม่ผ่านการตรวจ -> ใช้ร่างของระบบเรา
        if draft.get("plan"):
            written = _converse_with_gemini(history, draft)
            if written:
                return finish({**meta, "reply_text": "\n\n".join(written), "reply_parts": written,
                               "model_name": "gemini+manager", "model_version": _model()})
            print("คำตอบจาก Gemini ไม่ผ่านการตรวจ ใช้คำตอบของระบบเราแทน")
            return finish(result)
        if draft["intent"] == "advice":
            advice = _advise_with_gemini(history, draft)
            if advice:
                return finish({**meta, "reply_text": "\n\n".join(advice), "reply_parts": advice,
                               "model_name": "rule-based+gemini-advice", "model_version": _model()})
            print("คำแนะนำจาก Gemini ไม่ผ่านการตรวจ ใช้คำแนะนำจากคลังของเราแทน")
            return finish(result)
        polished = _polish_with_gemini(history, draft["reply_text"], draft["layout"], draft)
        if polished:
            return finish({**meta, "reply_text": "\n\n".join(polished), "reply_parts": polished,
                           "model_name": "rule-based+gemini", "model_version": _model()})
    except Exception as err:  # v29 พังแบบไหนก็ได้ -> ใช้คำตอบจากระบบเรา (เดิมจับแค่บางแบบ ที่เหลือกลายเป็น error 500)
        print(f"เรียก Gemini ไม่สำเร็จ ใช้คำตอบจากระบบเราแทน: {type(err).__name__}: {err}")
    return finish(result)


