def classify_topic_with_gemini(history: list[dict], candidates: list[str], prev_topic: str | None = None) -> str | None:
    """ให้ Gemini อ่านบทสนทนาแล้วเลือกหัวข้อ 1 อัน คืนชื่อหัวข้อ, "none" (ไม่ใช่หัวข้อไหน) หรือ None (Gemini ตอบไม่ได้)
    ส่งรายชื่อหัวข้อทั้งหมดไปด้วย แต่บอกว่า candidates คือหัวข้อที่ระบบในเครื่องคิดว่าน่าจะใช่"""
    user_msgs = [m["content"] for m in history if m["sender"] == "user"][-4:]
    key = f"{prev_topic}|" + "\n".join(user_msgs)
    if key in _TOPIC_CACHE:
        return _TOPIC_CACHE[key]
    topic_list = "\n".join(f"- {t}: {title_for(t)}" for t in KNOWLEDGE)
    system = (
        "คุณเป็นตัวจัดหมวดหมู่ข้อความภาษาไทย หน้าที่เดียวคือเลือกหัวข้อปัญหาที่ตรงกับเรื่องที่ผู้ใช้เล่ามากที่สุด\n"
        "ให้ความสำคัญกับข้อความล่าสุดของผู้ใช้มากที่สุด ข้อความก่อนหน้าใช้เป็นบริบท\n"
        "ถ้าข้อความล่าสุดสั้น คลุมเครือ หรือเป็นการพูดต่อเรื่องเดิม (เช่น 'ลองแล้วก็ยังเฉยๆ' 'แล้วทำไงดี') ให้ตอบหัวข้อที่กำลังคุยอยู่เดิม "
        "เปลี่ยนหัวข้อก็ต่อเมื่อข้อความล่าสุดเล่าเรื่องใหม่ที่ชัดเจน\n"
        "ถ้าผู้ใช้ปฏิเสธเรื่องใด (เช่น 'ไม่ได้โกรธ') ห้ามเลือกหัวข้อนั้น\n"
        "ถ้าข้อความมีทั้งเรื่องหน้าฉาก (เช่น โครงงาน สอบ) และต้นตอที่เป็นคน (เช่น พ่อแม่คาดหวัง เพื่อนเปรียบเทียบ) ให้เลือกหัวข้อของต้นตอ\n"
        "ถ้าไม่ใช่ปัญหาใดในรายการ (เช่น ทักทาย คุยเล่น) ให้ตอบ none\n"
        'ตอบเป็น JSON บรรทัดเดียวเท่านั้น เช่น {"topic": "sleep"} หรือ {"topic": "none"}\n\n'
        f"รายการหัวข้อ (ชื่อหัวข้อ: ความหมาย)\n{topic_list}"
    )
    convo = "\n".join(f"ข้อความที่ {i + 1}: {t}" for i, t in enumerate(user_msgs))
    prompt = (f"ข้อความของผู้ใช้ (ข้อความสุดท้ายคือล่าสุด)\n{convo}\n\n"
              f"หัวข้อที่กำลังคุยอยู่ก่อนหน้านี้: {prev_topic or 'ยังไม่มี'}\n"
              f"ระบบคาดว่าน่าจะเป็นหนึ่งในหัวข้อ: {', '.join(candidates)} (แต่เลือกหัวข้ออื่นในรายการได้ถ้าตรงกว่า)")
    text = _call_gemini(system, [{"role": "user", "parts": [{"text": prompt}]}], max_tokens=1024, temperature=0.0, timeout=10)
    m = re.search(r'"topic"\s*:\s*"([a-z_]+)"', text)
    picked = m.group(1) if m else None
    if picked != "none" and picked not in KNOWLEDGE:
        print(f"Gemini ตอบหัวข้อที่ไม่มีในระบบ: {text[:80]!r}")
        picked = None
    _TOPIC_CACHE[key] = picked
    if len(_TOPIC_CACHE) > 500:
        _TOPIC_CACHE.clear()
    return picked


