def analyze_assessment(answers: list[dict], total_score: int, severity_level: str, self_harm_risk_flag: bool) -> dict:
    if _api_key():
        try:
            return _analyze_with_gemini(answers, total_score, severity_level, self_harm_risk_flag)
        except Exception as err:  # v29 พังแบบไหนก็ได้ (เน็ต รูปแบบคำตอบแปลก ฯลฯ) -> ใช้ fallback ไม่ให้ผู้ใช้เห็น error
            print(f"เรียก Gemini ไม่สำเร็จ ใช้ fallback แทน: {type(err).__name__}: {err}")
    return _analyze_fallback(total_score, severity_level, self_harm_risk_flag)


def _as_text(value) -> str:
    """v29 Gemini บางครั้งตอบคำแนะนำเป็นลิสต์ ["...", "..."] แทนข้อความ -> รวมเป็นข้อความทีละบรรทัด
    (เดิมส่งลิสต์ลงฐานข้อมูลตรงๆ แล้ว SQLite บันทึกไม่ได้ ทำให้กดส่งแบบประเมินไม่สำเร็จ)"""
    if isinstance(value, list):
        return "\n".join(f"• {str(v).strip().lstrip('•-').strip()}" for v in value if str(v).strip())
    return str(value).strip() if value is not None else ""


def _analyze_with_gemini(answers, total_score, severity_level, self_harm_risk_flag) -> dict:
    answers_text = "\n".join(
        f"ข้อ {a['question_no']}: {a['question_text_th']} → ตอบระดับ {a['option_value']}/3" for a in answers
    )
    system = (
        "คุณเป็นผู้ช่วยด้านสุขภาพจิตในแอปคัดกรองโรคซึมเศร้า (ไม่ใช่แพทย์) "
        "สรุปผลแบบประเมิน 9Q ให้ผู้ใช้เข้าใจง่ายด้วยน้ำเสียงเห็นอกเห็นใจ ไม่ตัดสิน "
        "และให้คำแนะนำการดูแลตนเองเบื้องต้นที่ปลอดภัย ห้ามวินิจฉัยโรคหรือจ่ายยา\n"
        'ตอบกลับเป็น JSON เท่านั้นตามรูปแบบ: {"risk_label": "low_risk|at_risk|high_risk", '
        '"risk_probability": 0-1, "summary_text": "...", "recommendation_text": "..."}\n'
        "ทุกข้อความเป็นภาษาไทย (summary_text ~2-3 ประโยค, recommendation_text เป็นคำแนะนำ 3-5 ข้อ)"
    )
    user = (
        f"คะแนนรวม: {total_score}/27\n"
        f"ระดับความรุนแรงตามเกณฑ์ 9Q: {SEVERITY_LABEL_TH[severity_level]}\n"
        f"มีสัญญาณเสี่ยงทำร้ายตนเอง (ข้อ 9): "
        f"{'ใช่ — ต้องเน้นย้ำสายด่วน 1323 ในคำแนะนำ' if self_harm_risk_flag else 'ไม่มี'}\n\n"
        f"คำตอบรายข้อ:\n{answers_text}"
    )

    # temperature ต่ำๆ ตรงนี้ตั้งใจ — งานนี้ต้องได้ JSON ที่โครงสร้างถูกต้องแน่นอนทุกครั้ง
    # ไม่ต้องการความ "สร้างสรรค์" แบบแชท เดี๋ยว parse ไม่ออก
    text = _call_gemini(system, [{"role": "user", "parts": [{"text": user}]}], max_tokens=2048, temperature=0.3)
    match = re.search(r"\{[\s\S]*\}", text)
    parsed = json.loads(match.group(0) if match else text)
    if not isinstance(parsed, dict):
        raise ValueError("Gemini ไม่ได้ตอบเป็น JSON object")
    summary, reco = _as_text(parsed.get("summary_text")), _as_text(parsed.get("recommendation_text"))
    if not summary or not reco:
        raise ValueError("Gemini ตอบไม่มีสรุปหรือคำแนะนำ")
    label = parsed.get("risk_label")
    fallback = _analyze_fallback(total_score, severity_level, self_harm_risk_flag)
    if label not in ("low_risk", "at_risk", "high_risk") or (self_harm_risk_flag and label != "high_risk"):
        label = fallback["risk_label"]  # ระดับความเสี่ยงยึดเกณฑ์ของระบบเราเมื่อ Gemini ตอบแปลกหรือต่ำกว่าเกณฑ์
    try:
        prob = round(min(1.0, max(0.0, float(parsed.get("risk_probability")))), 3)
    except (TypeError, ValueError):
        prob = fallback["risk_probability"]
    if self_harm_risk_flag and "1323" not in reco:
        reco += "\n• หากรู้สึกไม่ปลอดภัยหรือมีความคิดทำร้ายตนเอง โทรสายด่วนสุขภาพจิต 1323 ได้ตลอด 24 ชั่วโมง"

    return {
        "risk_label": label,
        "risk_probability": prob,
        "summary_text": summary,
        "recommendation_text": reco,
        "model_name": "gemini",
        "model_version": _model(),
    }


def _analyze_fallback(total_score, severity_level, self_harm_risk_flag) -> dict:
    if self_harm_risk_flag or severity_level == "severe":
        risk_label = "high_risk"
    elif severity_level == "moderate":
        risk_label = "at_risk"
    else:
        risk_label = "low_risk"

    risk_probability = round(min(1.0, max(0.0, total_score / 27)), 3)

    summary_text = (
        f'คะแนนรวมของคุณอยู่ที่ {total_score} จาก 27 คะแนน ซึ่งจัดอยู่ในระดับ '
        f'"{SEVERITY_LABEL_TH[severity_level]}" ตามเกณฑ์ 9Q ของกรมสุขภาพจิต'
        + (
            "และคำตอบของคุณมีสัญญาณที่บ่งชี้ความคิดทำร้ายตนเอง ซึ่งเป็นเรื่องที่ควรได้รับการดูแลโดยเร็ว"
            if self_harm_risk_flag
            else ""
        )
    )

    base_tips = [
        "ลองพูดคุยกับคนที่ไว้ใจได้ เช่น ครอบครัวหรือเพื่อนสนิท",
        "พยายามนอนหลับให้เพียงพอและเป็นเวลา",
        "ออกกำลังกายเบาๆ หรือเดินเล่นกลางแจ้งอย่างน้อยวันละ 15-20 นาที",
        "ลองบันทึกความรู้สึกประจำวันเพื่อสังเกตตัวเอง",
    ]
    urgent_tips = [
        "หากรู้สึกไม่ปลอดภัยหรือมีความคิดทำร้ายตนเอง โทรสายด่วนสุขภาพจิต 1323 ได้ตลอด 24 ชั่วโมง โดยไม่มีค่าใช้จ่าย",
        "ควรปรึกษาจิตแพทย์หรือนักจิตวิทยาโดยเร็วที่สุด ไม่ต้องรอให้อาการแย่ลง",
        "หลีกเลี่ยงการอยู่คนเดียวในช่วงที่รู้สึกแย่มาก แจ้งคนใกล้ตัวให้ช่วยดูแล",
    ]

    if self_harm_risk_flag or severity_level == "severe":
        tips = urgent_tips + base_tips[:2]
    elif severity_level == "moderate":
        tips = base_tips + ["ลองปรึกษาผู้เชี่ยวชาญด้านสุขภาพจิตเพื่อรับคำแนะนำเพิ่มเติม"]
    else:
        tips = base_tips

    return {
        "risk_label": risk_label,
        "risk_probability": risk_probability,
        "summary_text": summary_text,
        "recommendation_text": "\n".join(f"• {t}" for t in tips),
        "model_name": "rule-based-fallback",
        "model_version": "v1",
    }


