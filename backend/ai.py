def _topic_context(draft: dict) -> str:
    """บอก Gemini ว่าระบบคิดว่าต้นตอ (หัวข้อหลัก) และเรื่องหน้าฉาก (หัวข้อรอง) คืออะไร"""
    primary, secondary = draft.get("topic"), draft.get("secondary_topic")
    lines = [f"หัวข้อหลัก/ต้นตอที่ระบบจับได้: {title_for(primary)}"]
    if secondary:
        lines.append(f"หัวข้อรอง/เรื่องหน้าฉากที่ผู้ใช้หยิบมาเล่า: {title_for(secondary)} (ใช้เป็นบริบทประกอบ ตอบให้ตรงกับต้นตอเป็นหลัก)")
    if draft.get("confidence") is not None and draft["confidence"] < 0.4:
        lines.append("ระบบยังไม่มั่นใจว่าจับหัวข้อถูก ถ้าบทสนทนาบอกเป็นอย่างอื่น ให้ยึดตามที่ผู้ใช้เล่า")
    return "\n".join(lines) + "\n"


