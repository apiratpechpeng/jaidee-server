GEMINI_URL_TEMPLATE = "https://generativelanguage.googleapis.com/v1beta/models/{model}:generateContent"


def _api_key() -> str:
    return os.environ.get("GEMINI_API_KEY", "").strip()


def _model() -> str:
    return os.environ.get("GEMINI_MODEL", "gemini-3.8-flash")


def ai_mode() -> str:
    return "gemini" if _api_key() else "rule-based-fallback"


def _call_gemini(system: str, contents: list[dict], max_tokens: int, temperature: float = 0.7, timeout: int = 30) -> str:
    # temperature สูง = คำตอบสุ่ม/หลากหลายขึ้น (เหมาะกับแชทที่อยากให้ฟังดูเป็นธรรมชาติ ไม่พูดซ้ำเดิม)
    # temperature ต่ำ = คำตอบนิ่ง/คาดเดาได้มากขึ้น (เหมาะกับงานที่ต้องการโครงสร้างแน่นอน เช่น การตอบเป็น JSON)
    # topP/topK ช่วยจำกัดขอบเขตคำที่โมเดลจะสุ่มเลือกต่อไป ไม่ให้หลุดจนคำตอบแปลกเกินไป
    url = f"{GEMINI_URL_TEMPLATE.format(model=_model())}?key={_api_key()}"
    # ความเป็นส่วนตัว: ตัดเบอร์โทร อีเมล ชื่อโรงเรียน ฯลฯ ออกจากข้อความทุกครั้งก่อนส่งออกนอกเครื่อง (ดู privacy.py)
    contents = [{**c, "parts": [{**p, "text": scrub(p["text"])} if "text" in p else p for p in c.get("parts", [])]}
                for c in contents]
    payload = json.dumps(
        {
            "contents": contents,
            "systemInstruction": {"parts": [{"text": system}]},
            "generationConfig": {
                "maxOutputTokens": max_tokens,
                "temperature": temperature,
                "topP": 0.95,
                "topK": 40,
            },
        }
    ).encode("utf-8")

    req = urllib.request.Request(
        url,
        data=payload,
        method="POST",
        headers={"content-type": "application/json"},
    )
    with urllib.request.urlopen(req, timeout=timeout) as resp:
        body = json.loads(resp.read().decode("utf-8"))

    cand = body["candidates"][0]
    # รวมทุก part (ข้าม part ที่เป็น "thought" ของโมเดลที่คิดก่อนตอบ) ไม่ใช่เอาแค่ part แรก
    parts = cand.get("content", {}).get("parts", [])
    text = "".join(p.get("text", "") for p in parts if not p.get("thought"))
    # ถ้าโดนตัดเพราะ token หมด ให้ตัดเหลือถึงท้ายประโยคสุดท้ายที่จบสมบูรณ์ ดีกว่าให้ขาดกลางคำ
    if cand.get("finishReason") == "MAX_TOKENS":
        print("คำเตือน: Gemini ตอบถูกตัดเพราะ maxOutputTokens หมด — ลองเพิ่มค่า max_tokens")
        cut = max(text.rfind(c) for c in ("?", "!", "ๆ ", "\n", " ", "ะ", "นะ"))
        if cut > len(text) * 0.5:
            text = text[: cut + 1]
    return text


