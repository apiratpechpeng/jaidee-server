def _fact(rec: dict) -> str | None:
    """เหตุการณ์ที่ถูกแกล้งด้วยคำของผู้ใช้ (บุรุษที่ 1 แบบ หนู/ผม) ไว้ใส่ในประโยคตัวอย่าง ตัดส่วนที่พูดเรื่องครู/ไม่อยากไปโรงเรียนออก"""
    for t in rec["texts"]:
        key = S._first(t, S.W["hurt"])
        if not key:
            continue
        f = S._strip_fillers(S._clause(S.clean(t), key, 80))
        f = re.split(r"\s*(เคย)?(บอก|ฟ้อง|เล่าให้)ครู|\s*ครู\S{0,6}(ไม่ช่วย|เฉย)|\s*(ตอนนี้)?\s*ไม่อยากไปโรงเรียน", f)[0]
        f = re.sub(r"(" + "|".join(S.SELF_WORDS) + r")", "หนู/ผม", f)
        f = re.sub(r"\s*(เลย|แล้ว)$", "", f).strip()
        return f or None
    return None


