def _options_for(area: str, rec: dict, tried_text: str = "") -> list[tuple]:
    kinds = list(reversed(rec["kinds"]))  # ชนิดล่าสุดมาก่อน
    if area == "path":
        kinds = ["path"] + kinds
    if "hurt" in kinds:
        kinds = [k for k in kinds if k != "appearance"]  # โดนล้อรูปร่าง: ใช้วิธีรับมือการถูกแกล้ง ไม่ใช่เรื่องดูแลภาพลักษณ์
    out = []
    for k in kinds:
        for o in OPTIONS.get(k, []):
            if o not in out and not any(key in tried_text for key in o[2]):
                out.append(o)
    given = rec.get("given", [])
    fresh = [o for o in out if o not in given]
    return (fresh or out)[:3]


