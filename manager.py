def _is_yes(t: str) -> bool:
    t = t.strip().lower()
    return not any(n in t for n in NO_WORDS) and "ไม่" not in t[:4] and any(w in t for w in YES_WORDS)


def _is_no(t: str) -> bool:
    return any(n in t for n in NO_WORDS)


def _pick(t: str, opts: list[tuple]) -> int | None:
    for i, rx in enumerate(PICK_RE):
        if i < len(opts) and rx.search(t):
            return i
    for i, o in enumerate(opts):
        if any(k in t for k in o[2]):
            return i
    return None


