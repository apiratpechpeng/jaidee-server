    (r"ไม่รู้จะเอา|ไม่รู้จะทำ|ไม่มีทาง|ยังไม่รู้", "{echo} พอยังมองไม่เห็นทาง ใจก็ยิ่งกังวลเป็นธรรมดาเลยครับ"),
