def _area_of(kind: str, text: str, person: str | None, all_text: str) -> str:
    if kind == "compare":
        return "family" if any(k in text for k in ("แม่", "พ่อ", "ที่บ้าน", "พี่", "น้อง", "ลูกคนอื่น", "ลูกบ้านอื่น")) else "study"
    if kind in ("conflict", "hurt", "decision", "excluded", "unheard"):
        if person in FAMILY_PEOPLE or (person is None and any(k in text for k in ("แม่", "พ่อ", "ที่บ้าน"))):
            return "family"
        if person in LOVE_PEOPLE:
            return "love"
        return "path" if kind == "decision" else "friends"
    if kind == "result" and ("แค่" in text or "อยากเป็น" in all_text or "ความฝัน" in all_text):
        return "path"
    return AREA.get(kind, "self")


def _segments(t: str, kinds: list[str], person, all_text: str) -> list[tuple[str, str | None]]:
    """แบ่งข้อความเป็นท่อน [(ข้อความ, ด้าน)] ตามช่องว่าง: ท่อนที่พูดเรื่องด้านใหม่เริ่มท่อนใหม่ ท่อนที่ไม่มีเรื่องต่อท้ายท่อนเดิม"""
    chunks = [c for c in re.split(r"\s+|,", t) if c]
    segs: list[list] = []
    for c in chunks:
        ks = [k for k in S.kinds_of(c) if k in kinds]
        area = _area_of(ks[0], c, S._first(c, S.PEOPLE) or person, all_text) if ks else None
        prev_vague = bool(segs) and segs[-1][1] is None and any(w in segs[-1][0] for ws in VAGUE.values() for w in ws)
        if segs and (area is None or area == segs[-1][1] or (segs[-1][1] is None and not prev_vague)):
            segs[-1][0] += " " + c
            segs[-1][1] = segs[-1][1] or area
        else:
            segs.append([c, area])
    return [(a, b) for a, b in segs]


def analyze(text: str, all_text: str = "") -> dict:
    """{ด้าน: {"kinds": [...], "text": ท่อนข้อความของด้านนั้น, "person": ...}} เรียงตามลำดับที่พูดถึง"""
    t = S.clean(text)
    low = t.lower()
    kinds = S.kinds_of(t)
    person = S._first(t, S.PEOPLE)
    segs_a = _segments(t, kinds, person, all_text)
    segs = [x for x, _ in segs_a]
    out: dict[str, dict] = {}
    pos = {}
    for k in kinds:
        seg = next((sg for sg in segs if k in S.kinds_of(sg)), None)
        sp = S._first(seg, S.PEOPLE) if seg else None
        area = _area_of(k, seg or t, sp or person, all_text)
        seg_area = next((sa for sg, sa in segs_a if sg == seg), None)
        if seg_area and seg_area != area:
            area = seg_area  # อยู่ท่อนเดียวกับเรื่องอื่น (เช่น "อยากเรียนศิลปะแต่พ่อบังคับให้เรียนหมอ") = เรื่องเดียวกัน
        if len({sa for _, sa in segs_a if sa}) <= 1:
            seg = t  # เรื่องเดียวในข้อความ: ใช้ทั้งข้อความ
        rec = out.setdefault(area, {"kinds": [], "segs": [], "person": None})
        rec["kinds"].append(k)
        if seg and seg not in rec["segs"]:
            rec["segs"].append(seg)
        rec["person"] = rec["person"] or sp
        words = S.W.get(k, [])
        pos[area] = min(pos.get(area, 10 ** 6), min((low.find(w) for w in words if w in low), default=10 ** 6))
    for area, words in VAGUE.items():
        if area in out:
            continue
        # คำลอยๆ ที่อยู่ท่อนเดียวกับเรื่องอื่น (เช่น "หมาที่บ้านตาย") ไม่นับเป็นอีกเรื่อง
        hit = [w for w in words if any(w in sg and sa in (None, area) for sg, sa in segs_a)]
        if hit:
            out[area] = {"kinds": [], "segs": [sg for sg in segs if any(w in sg for w in hit)], "person": None, "vague": True}
            pos[area] = min(low.find(w) for w in hit)
    if len(out) == 1:
        for rec in out.values():
            rec["person"] = rec["person"] or person
    for rec in out.values():
        rec["text"] = " ".join(rec["segs"]) if rec["segs"] else t
    return dict(sorted(out.items(), key=lambda kv: pos.get(kv[0], 0)))


def _subject(texts) -> str | None:
    for t in reversed(texts):
        hit = S._first(t, [w for w, _ in S.SUBJECTS])
        if hit and dict(S.SUBJECTS)[hit] != "ที่บ้าน":
            return dict(S.SUBJECTS)[hit]
    return None


def label(area: str, rec: dict) -> str:
    kinds = rec["kinds"]
    subj = _subject(rec["texts"]) or "งาน"
    who = rec.get("person") or {"family": "พ่อแม่", "love": "แฟน", "friends": "เพื่อน"}.get(area, "คนใกล้ตัว")
    if not kinds:
        return _subject(rec["texts"]) or VAGUE_NAME.get(area, "นี้")
    main = next((k for k in kinds if k not in FEELING_KINDS), kinds[0])
    if main == "excluded" and area == "love":
        return "แฟนที่ไม่ค่อยตอบหรือไม่สนใจ"
    return LABEL.get(main, "นี้").format(subj=subj, who=who)


def _join_labels(labels: list[str]) -> str:
    labels = [f"เรื่อง{x}" for x in labels]
    if len(labels) <= 2:
        return " และ".join(labels) if len(labels) == 2 else labels[0]
    return " ".join(labels[:-1]) + " และ" + labels[-1]


