def _flow_action(fl: dict) -> str:
    if fl["stage"] == "options":
        return "options"
    return "advice_step" if any("อย่างแรก" in p for p in fl["parts"]) else "support"


def _render_opts(opts: list[tuple]) -> str:
    words = ["อย่างแรก", "อย่างที่สอง", "อีกอย่างคือ"]
    return " ".join(f"{w} {o[0]}" for w, o in zip(words, opts)) + "ครับ"


def _flow(rec: dict, t: str, area: str, first: bool, reflect: str = "") -> dict | None:
    """หาขั้นตอนต่อที่ตรงกับเรื่องนี้ -> {"parts", "stage", "id"} หรือ None"""
    done = rec.setdefault("flow_done", [])
    texts = " ".join(rec["texts"])
    slots = None
    for e in FLOW:
        if bool(e.get("first")) != first or not any(k in rec["kinds"] for k in e["kinds"]):
            continue
        if any(k not in rec["kinds"] for k in e.get("need_kinds", [])):
            continue
        whens = e.get("when") or []
        if isinstance(whens, str):
            whens = [whens]
        if any(not re.search(w, t.lower()) for w in whens):
            continue
        if e.get("need") and not re.search(e["need"], texts):
            continue
        if e.get("after") and e["after"] not in done:
            continue
        slots = slots or _slots(rec, t, area)
        key = e["id"] + (":" + slots["topic_name"] if e["id"] == "topic" and slots["topic_name"] else "")
        if key in done:
            continue
        vals = dict(slots, reflect=reflect)
        names = [n for p in e["parts"] for n in re.findall(r"\{(\w+)\}", p) if n != "opts"]
        if any(vals.get(n) is None for n in names):
            continue  # ไม่มีข้อมูลพอสำหรับข้อนี้
        opts = None
        if e.get("opts"):
            key_o = "entrance_cmp" if e["opts"] == "entrance_cmp_or" and "compare" in rec["kinds"] else e["opts"]
            opts = OPTIONS[key_o]
            rec["opts"] = opts
            rec["given"] = rec.get("given", []) + [o for o in opts if o not in rec.get("given", [])]
        parts = []
        for p in e["parts"]:
            out = p.replace("{opts}", _render_opts(opts) if opts else "")
            for n in names:
                out = out.replace("{" + n + "}", str(vals[n]))
            parts.append(re.sub(r"\s+", " ", out).strip())
        done.append(key)
        return {"parts": [p for p in parts if p], "stage": e.get("stage", "followed"), "id": e["id"]}
    return None


