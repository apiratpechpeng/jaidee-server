TRIED_KNOWN = re.compile(r"ยังไม่ได้(ลอง|ถาม|บอก|คุย|ขอโทษ)|ไม่เคย(ลอง|ถาม|บอก|คุย)|ลอง\S{0,12}แล้ว|ถามแล้ว|บอกแล้ว|คุยแล้ว|ไม่กล้า(ถาม|บอก)")


def _tried_known(rec: dict) -> str:
    """ผู้ใช้เล่าไปแล้วว่าลอง/ยังไม่ได้ลองอะไร -> ข้อความนั้น (ไม่ต้องถามซ้ำ)"""
    return next((t for t in reversed(rec["texts"]) if TRIED_KNOWN.search(t)), "")


def _tried_question(rec: dict) -> str:
    k = next((k for k in reversed(rec["kinds"]) if k in TRIED), None)
    return TRIED[k] if k else TRIED_DEFAULT


def _options_parts(area: str, rec: dict, text: str, lead: str) -> list[str]:
    tried_pos = bool(re.search(r"ลองแล้ว|เคยลอง|ถามแล้ว|บอกแล้ว|คุยแล้ว|ทำแล้ว", text)) and not re.search(r"ยังไม่|ไม่เคย", text)
    opts = _options_for(area, rec, text if tried_pos else "")
    rec["given"] = rec.get("given", []) + [o for o in opts if o not in rec.get("given", [])]
    rec["opts"] = opts
    if not opts:
        return []
    first = f"{lead} อย่างแรก {opts[0][0]}ครับ".strip()
    rest = " ".join(f"{w} {o[0]}" + ("ครับ" if i == len(opts[1:]) - 1 else "") for i, (w, o) in
                    enumerate(zip(["อย่างที่สอง", "อีกอย่างคือ"], opts[1:])))
    parts = [first] + ([rest] if rest else [])
    parts.append("ข้อไหนที่พอจะลองได้มากที่สุดครับ เดี๋ยวช่วยวางขั้นแรกด้วยกัน")
    return parts


def _lead_for_tried(text: str) -> str:
    if re.search(r"ยังไม่|ไม่เคย|ไม่ได้ลอง|ไม่ได้ถาม|ไม่ได้บอก|ไม่กล้า|ไม่มี|ไม่รู้", text):
        return "ยังไม่ได้ลองก็ไม่เป็นไรเลยครับ เริ่มจากตรงนี้ได้"
    if re.search(r"ลอง|เคย|แล้ว", text):
        return "ลองมาแล้วแต่ยังไม่ดีขึ้น แสดงว่าคุณพยายามอยู่นะครับ ลองดูทางอื่นเพิ่มกัน"
    return "ขอบคุณที่เล่าให้ฟังครับ ลองดูทางที่พอทำได้แบบนี้นะ"


def _advance(state: _State, text: str, advice: bool, topic: str | None) -> dict | None:
    """ไล่ 1 ข้อความผู้ใช้: อัปเดตสถานะ แล้วคืน {"parts", "action", "area"} หรือ None (ให้ chatbot ตอบแบบเดิม)"""
    state.turn += 1
    t = S.clean(text)
    low = t.lower()
    all_text = " ".join(" ".join(r["texts"]) for r in state.areas.values()) + " " + t
    found = analyze(t, all_text)
    # ความรู้สึกล้วนๆ (เหงา ไม่ดีพอ หมดแรง) ระหว่างคุยเรื่องอื่น = ส่วนหนึ่งของเรื่องที่คุยอยู่
    if state.active:
        for a in list(found):
            if a != state.active and found[a]["kinds"] and all(k in FEELING_KINDS for k in found[a]["kinds"]):
                found.pop(a)
            elif a != state.active and found[a].get("vague") and not ("ทั้ง" in t and len(found) >= 2):
                found.pop(a)  # พูดถึงเรื่องเรียน/ที่บ้านลอยๆ ระหว่างเล่า = รายละเอียดของเรื่องเดิม
    new = [a for a in found if a not in state.areas]
    choice_kinds = ("decision", "dream", "expectation", "future")
    decision_q = "ควร" in low and any(q in low for q in ("ไหม", "มั้ย", "หรือ")) and (
        any(k in choice_kinds for r in found.values() for k in r["kinds"]) or
        bool(state.active and any(k in choice_kinds for k in state.areas[state.active]["kinds"])))
    advice = (advice or bool(HELP_RE.search(low))) and not decision_q

    def add(area):
        rec = found[area]
        if area in state.areas:
            old = state.areas[area]
            old["kinds"] += [k for k in rec["kinds"] if k not in old["kinds"]]
            old["texts"].append(rec["text"])
            old["person"] = old["person"] or rec.get("person")
        else:
            state.areas[area] = {"kinds": list(rec["kinds"]), "texts": [rec["text"]], "person": rec.get("person"),
                                 "stage": "new", "first": state.turn}
        return state.areas[area]

    def reply(parts, action, area, stage=None):
        if area and stage:
            state.areas[area]["stage"] = stage
        state.said += "\n" + "\n".join(parts)
        return {"parts": parts, "action": action, "area": area}

    def focus(area, link=""):
        rec = state.areas[area]
        state.active = area
        r = _reflect(area, rec, topic, state)
        if link:
            r = link + " " + r
        if rec["stage"] == "new":
            fl = _flow(rec, t, area, True, r)
            if fl:
                return reply(fl["parts"], _flow_action(fl), area, fl["stage"])
        parts = [r]
        w = S.worth(_st(rec), state.said)
        if w:
            parts.append(w)
        if state.advice_pending and rec["kinds"] and not any(k in rec["kinds"] for k in ("hurt", "unfair", "illness", "conflict")) \
                and rec["first"] < state.turn:
            q = _tried_question(rec)
            parts.append(q)
            state.advice_pending = False
            return reply(parts, "ask_tried", area, "tried")
        if advice and not rec["kinds"]:
            state.advice_pending = True
        q = _question(area, rec, state)
        parts.append(q)
        return reply(parts, "reflect", area, "offered" if any(w in q for w in OFFER_WORDS) else "asked")

    # 1) เล่าหลายเรื่องในข้อความเดียว
    counted = [a for a in found if found[a]["kinds"] or found[a].get("vague")]
    all_k = [k for a in counted for k in found[a]["kinds"]]
    if len(counted) >= 2 and "expectation" in all_k and ("dream" in all_k or "compare" in all_k) \
            and all(a in ("family", "path", "study") for a in counted):
        # v26 ที่บ้านอยากให้เรียน X + เราอยากเรียน Y + ถูกเปรียบเทียบ/คะแนน = เรื่องแรงกดดันจากที่บ้านเรื่องเดียว
        merged = {"kinds": [], "segs": [t], "person": None, "text": t}
        for a in counted:
            merged["kinds"] += [k for k in found[a]["kinds"] if k not in merged["kinds"]]
            merged["person"] = merged["person"] or found[a].get("person")
        found = {"family": merged, **{a: r for a, r in found.items() if a not in counted}}
        new = [a for a in found if a not in state.areas]
        counted = ["family"]
    first_time = not state.areas
    if len([a for a in counted if a in new or first_time]) >= 2:
        for a in counted:
            add(a)
        urgent = next((a for a in counted if any(k in found[a]["kinds"] for k in URGENT)), None)
        if urgent:
            others = [label(a, state.areas[a]) for a in counted if a != urgent]
            state.pending = None
            return focus(urgent, f"ทั้งที่มี{_join_labels(others)}อยู่แล้ว")
        state.pending = list(counted)
        state.active = None
        labels = [label(a, state.areas[a]) for a in counted]
        summary = f"ฟังแล้วตอนนี้มีหลายเรื่องเข้ามาพร้อมกันเลยนะครับ ทั้ง{_join_labels(labels)} แบกไว้พร้อมกันแบบนี้คงเหนื่อยมาก"
        if advice:
            summary += " อยากช่วยคิดทีละเรื่องนะครับ"
        return reply([summary, "อยากเริ่มคุยเรื่องไหนก่อนครับ หรือเรื่องไหนที่หนักใจที่สุดตอนนี้"], "multi", None)

    # 2) ตอบว่าจะเริ่มเรื่องไหน
    if state.pending:
        pend = state.pending
        chosen = next((a for a in found if a in pend), None)
        if chosen is None:
            for i, rx in enumerate(PICK_RE):
                if i < len(pend) and (rx.search(low) or re.search(r"เรื่อง(แรก|ที่ 1)" if i == 0 else r"เรื่องที่ ?%d|เรื่องที่สอง" % (i + 1), low)):
                    chosen = pend[i]
                    break
        if chosen is None:
            for a in pend:
                lab = label(a, state.areas[a])
                if any(w in low for w in re.findall(r"[ก-๙A-Za-z]{2,}", lab)[:1]) or \
                        any(p in low for p in ([state.areas[a].get("person")] if state.areas[a].get("person") else [])):
                    chosen = a
                    break
        auto = False
        if chosen is None and re.search(r"ไม่รู้|ทั้งคู่|ทั้งหมด|ทุกเรื่อง|เรื่องไหนก็ได้|แล้วแต่", low):
            chosen = sorted(pend, key=lambda a: (not any(k in state.areas[a]["kinds"] for k in URGENT), AREA_ORDER.index(a)))[0]
            auto = True
        if chosen:
            state.pending = None
            if chosen in found and found[chosen]["kinds"]:
                add(chosen)
            link = f"งั้นเริ่มจากเรื่อง{label(chosen, state.areas[chosen])}ก่อนนะครับ" if auto else ""
            return focus(chosen, link)

    # 3) เรื่องใหม่ 1 เรื่อง
    if new and decision_q and first_time:
        a = new[0]
        add(a)
        state.active = a
        state.areas[a]["decided_q"] = True
        return reply([_reflect(a, state.areas[a], topic, state),
                      "ตอนนี้ในใจคุณเอนไปทางไหนมากกว่ากันครับ แล้วอะไรที่ทำให้ยังลังเลอยู่"], "decision", a, "asked")
    if new and (found[new[0]]["kinds"] or first_time):
        a = new[0]
        prev = state.active
        rec = add(a)
        for other in found:
            if other != a and other in state.areas:
                add(other)
        link = ""
        answer = re.match(r"\s*(เพราะ|ตั้งแต่|ก็เพราะ|มันเริ่มจาก|เริ่มจาก|คือ)", t)
        prev_feeling = prev and all(k in FEELING_KINDS for k in state.areas[prev]["kinds"])
        if prev and prev != a and not answer and not prev_feeling and not (a == "path" and "decision" in state.areas[prev]["kinds"]):
            link = f"นอกจาก{_join_labels([label(prev, state.areas[prev])])}แล้ว ยังมีเรื่อง{AREA_NAME[a]}อีก หนักหลายทางเลยนะครับ"
        if rec["stage"] == "new" and rec["kinds"]:
            fl = _flow(rec, t, a, True, (link + " " if link else "") + _reflect(a, rec, topic, state))
            if fl:
                state.active = a
                return reply(fl["parts"], _flow_action(fl), a, fl["stage"])
        if advice and rec["kinds"] and not state.advice_pending:
            if first_time and any(k in rec["kinds"] for k in ("hurt", "unfair", "illness", "decision", "conflict")):
                state.advice_pending = True  # เรื่องที่ต้องรู้รายละเอียดก่อน: ถามก่อน
                return focus(a, link)
            if first_time:
                state.active = a
                parts = [(link + " " if link else "") + _reflect(a, rec, topic, state), _tried_question(rec)]
                return reply(parts, "ask_tried", a, "tried")
        if advice and not rec["kinds"]:
            state.active = a
            state.advice_pending = True
            subj = label(a, rec)
            ex = ASK_SPECIFIC_EX.get(a, "")
            parts = [(f"อยากช่วยคิดทางออกเรื่อง{subj}ด้วยครับ แต่ขอเข้าใจให้ตรงก่อนนิดนึง"),
                     f"ตอนนี้ติดตรงไหนมากที่สุดครับ" + (f" เช่น {ex}" if ex else "")]
            return reply(parts, "ask_specific", a, "asked")
        return focus(a, link)

    # 4) ต่อเรื่องเดิม
    switch = next((x for x in found if x in state.areas and x != state.active and found[x]["kinds"]), None)
    if switch:
        add(switch)
        return focus(switch)
    a = state.active
    if a is None:
        if state.areas and advice:
            a = list(state.areas)[-1]
            state.active = a
        else:
            return None
    rec = state.areas[a]
    new_kinds = [k for k in (found.get(a, {}).get("kinds") or []) if k not in rec["kinds"]]
    if a in found:
        add(a)
    else:
        rec["texts"].append(t)
    stage = rec["stage"]

    fl = _flow(rec, t, a, False)
    if fl:
        return reply(fl["parts"], _flow_action(fl), a, fl["stage"])
    if decision_q:
        if rec.get("decided_q"):
            if "choice" not in rec["kinds"] and "decision" not in rec["kinds"]:
                rec["kinds"].append("choice")
            parts = _options_parts(a, rec, "", "ผมไม่อยากตัดสินแทนคุณนะครับ แต่มีวิธีช่วยให้ตัดสินใจได้ชัดขึ้น")
            return reply(parts, "options", a, "options")
        rec["decided_q"] = True
        if "decision" in rec["kinds"]:
            st = _st(rec)
            parts = [S.reflect(st, topic, state.said) or _reflect(a, rec, topic, state),
                     S.question(st, topic, state.said, False) or OFFER]
        else:
            parts = ["เป็นการตัดสินใจที่ใหญ่มากเลยนะครับ ไม่แปลกที่คุณลังเล เพราะเรื่องนี้กระทบอนาคตคุณโดยตรง ผมไม่อยากตัดสินแทนคุณ แต่ช่วยคิดไปด้วยกันได้",
                     "ตอนนี้ในใจคุณเอนไปทางไหนมากกว่ากันครับ แล้วอะไรที่ทำให้ยังลังเลอยู่"]
        return reply(parts, "decision", a, stage)
    if stage in ("options", "planned"):
        opts = rec.get("opts") or []
        hinted = _pick(low, opts) if stage == "options" else None
        rejected = any(w in low for w in REJECT_WORDS) and not any(rx.search(low) for rx in PICK_RE)
        pick = None if rejected else hinted
        if stage == "options" and opts and not rejected and not advice and (pick is not None or _is_yes(low)):
            o = opts[pick or 0]
            rec["chosen"] = o
            parts = [f"ดีเลยครับ เริ่มจากก้าวเล็กๆ ก่อนนะ ขั้นแรกที่ทำได้วันนี้คือ {o[1]}",
                     "ไม่ต้องทำให้สมบูรณ์ แค่เริ่มก็นับแล้วครับ พอจะทำได้ไหม หรือมีอะไรที่ทำให้ยังไม่กล้าเริ่ม"]
            return reply(parts, "plan", a, "planned")
        if rejected or advice:
            more = [o for o in _options_for(a, rec) if o not in rec.get("given", [])]
            if more and advice:
                parts = _options_parts(a, rec, t, "ได้ครับ ลองดูอีกทางนะ")
                return reply(parts, "options", a, "options")
            small = (opts[hinted] if hinted is not None and hinted < len(opts) else None) or rec.get("chosen") or (opts[-1] if opts else None)
            lead = ("ไม่กล้าก็เข้าใจได้เลยครับ เรื่องแบบนี้ต้องใช้ใจเยอะ" if "ไม่กล้า" in low or "กลัว" in low
                    else "ไม่เป็นไรเลยครับ ไม่จำเป็นต้องใช้วิธีที่ไม่เหมาะกับคุณ")
            mid = (f"ลองแบบที่เล็กกว่านี้ไหมครับ แค่{small[1]} ยังไม่ต้องทำจริงทั้งหมดก็ได้" if small
                   else "บางทีแค่เล่าให้คนที่ไว้ใจฟังก่อนก็นับเป็นก้าวแรกแล้วนะครับ")
            parts = [lead + " " + mid, "ตรงไหนที่ทำให้รู้สึกว่ายากที่สุดครับ บอกได้เลย เดี๋ยวช่วยปรับให้เหมาะกับคุณ"]
            return reply(parts, "alt", a, "options")
        if stage == "planned":
            other = [x for x in state.areas if x != a and state.areas[x]["stage"] in ("new", "asked")]
            tail = (f"ถ้าพร้อมเมื่อไหร่ เรากลับไปคุยเรื่อง{label(other[0], state.areas[other[0]])}ด้วยกันก็ได้นะครับ"
                    if other else "ระหว่างนี้มีเรื่องอื่นที่ค้างอยู่ในใจอยากเล่าอีกไหมครับ")
            return reply(["เยี่ยมเลยครับ แค่ตั้งใจจะลองก็เป็นก้าวที่ดีแล้ว ลองแล้วเป็นยังไงกลับมาเล่าให้ฟังได้เสมอนะ", tail],
                         "after_plan", a, "planned")
    if advice:
        if not rec["kinds"]:
            state.advice_pending = True
            ex = ASK_SPECIFIC_EX.get(a, "")
            parts = [f"อยากช่วยคิดทางออกเรื่อง{label(a, rec)}ด้วยครับ แต่ขอเข้าใจให้ตรงก่อนนิดนึง",
                     "ตอนนี้ติดตรงไหนมากที่สุดครับ" + (f" เช่น {ex}" if ex else "")]
            return reply(parts, "ask_specific", a, "asked")
        lead = _lead_for_tried(t) if stage == "tried" else f"ได้ครับ ลองดูทางที่พอทำได้เรื่อง{label(a, rec)}กันนะครับ"
        parts = _options_parts(a, rec, t if stage == "tried" else "", lead)
        state.advice_pending = False
        return reply(parts, "options", a, "options")
    if stage == "tried":
        parts = _options_parts(a, rec, t, _lead_for_tried(t))
        return reply(parts, "options", a, "options")
    if stage == "offered" and _is_yes(low) and not new_kinds:
        known = _tried_known(rec)
        if known:
            return reply(_options_parts(a, rec, known, _lead_for_tried(known)), "options", a, "options")
        return reply([_tried_question(rec)], "ask_tried", a, "tried")
    if stage == "offered" and _is_no(low):
        q = _question(a, rec, state)
        return reply(["ได้เลยครับ ไม่ต้องรีบหาทางออกก็ได้ เล่าต่อได้ตามสบายเลยนะ", q if q != OFFER else "ตอนนี้อะไรที่ค้างอยู่ในใจที่สุดครับ"],
                     "listen", a, "asked")
    if new_kinds:
        return focus(a)
    if state.advice_pending and rec["kinds"]:
        state.advice_pending = False
        return reply([_detail_reflect(rec, t, topic, state), _tried_question(rec)], "ask_tried", a, "tried")
    r = _detail_reflect(rec, t, topic, state)
    q = _question(a, rec, state)
    return reply([r, q], "detail", a, "offered" if any(w in q for w in OFFER_WORDS) else "asked")


def step(history: list[dict], advice_fn, topic: str | None = None) -> dict | None:
    """ไล่ทุกข้อความผู้ใช้ตั้งแต่ต้น แล้วคืนคำตอบของข้อความล่าสุด (หรือ None ถ้าไม่ใช่เรื่องปัญหา)"""
    users = [m["content"] for m in history if m["sender"] == "user"]
    state = _State()
    out = None
    for i, u in enumerate(users):
        out = _advance(state, u, advice_fn(u), topic if i == len(users) - 1 else None)
    if out:
        out["state"] = {"areas": {a: {"label": label(a, r), "kinds": r["kinds"], "stage": r["stage"]} for a, r in state.areas.items()},
                        "active": state.active, "pending": state.pending}
    return out
